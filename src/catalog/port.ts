// ВР-1, К1 — порт каталога (решение **П38** от 22.11.2026, п. 1–3; правило планов № 1 «только через порт»,
// инвариант 2 приложения).
//
// Своей модели товара у приложения **нет**. Каноническая модель каталога — это **К8 ядра**
// (`@kuzin4u/agentic-core/catalog`: типы, валидаторы, 22 кода ошибок модели, правило A5, реестр `CATALOG_DIAG`), и
// ядро агента её реэкспортирует. Поэтому здесь нет ни одного **своего объявления** понятия, которое есть в К8:
// товар, магазин, факты, коды и сигналы берутся типами ядра (Р-1511 — перечни и формы из источника).
//
// Нормализации здесь тоже нет. Форму эмулятора витрин (`snake_case`, `merchant_id ≠ id` витрины, цена и валюта
// отдельными полями, возраст карточки вместо времени обновления) переводит в К8 **адаптер витрин ядра**
// (`agentic-buyer-ref/src/agent/adapters/shops/adapter.ts`, Р42 п. 2, Р54 п. 4). Приложение получает **факты**, а не
// форму источника, и поэтому от формы не зависит: переведёт ли когда-нибудь PS-К1 эмулятор в К8 — для этого модуля
// безразлично (П38 п. 3).
//
// Откуда приходят факты: `createAgentCore(...).shops({ baseUrl, fetch }).offers` — порт стадии 2 ядра; подробнее —
// у реэкспорта `OfferSource` ниже.
//
// Почему ввоз именно через ядро агента, а не прямо из `@kuzin4u/agentic-core/catalog` (П38 п. 2): подмодули пакета
// (`/catalog`, `/pao`, `/diag`, `/merchant`) запрещены стражем границы — в них протокол платформы, и точечное
// исключение П7 дополнения 2 покрывает только основной вход и только два имени канонизации
// (`tests/demo/faulty.test.ts`). Ядро агента К8 реэкспортирует, и расширять исключение не нужно.

/**
 * Модель каталога — типы **К8 ядра**, реэкспортом.
 *
 * Реэкспорт, а не «импортировать у себя и не показывать»: модулям ВР-1 (учёт отклонённого, тексты, просев
 * инварианта 1) нужны те же типы, и ходить за ними каждому в ядро значило бы размазать границу по файлам — тогда
 * страж пришлось бы проверять в каждом, а не в одном месте. Здесь же видно, что приложение **не добавило к модели
 * ни одного поля**.
 *
 * - `CatalogShop`, `CatalogProduct` — магазин и товар К8 (`gtin`, `brand`, `model`, `attributes`, `delivery`,
 *   `availability`, `price` парой «минимальные единицы + валюта», `updatedAt`);
 * - `ProductFacts` — товар после проверок ядра: `issues` (ошибки модели) и `signals` (сигналы A5);
 * - `CatalogFacts` — магазин, `shopIssues`, товары и `dropped`;
 * - `CatalogIssueCode`, `A5SignalCode` — коды ядра; своих перечней приложение не держит.
 */
export type {
  A5SignalCode,
  CatalogFacts,
  CatalogIssueCode,
  CatalogProduct,
  CatalogShop,
  LiveCheckCode,
  ProductFacts,
} from "agentic-buyer-ref/src/agent/catalog/index.js";

/**
 * Исход поиска по одной витрине — тоже тип ядра (`agentic-buyer-ref/src/agent/ports/shop.js`).
 *
 * - `ShopOffers` — витрина ответила: `facts` в модели К8, `merchantId` для поручения и заказа, `inContour` — зона
 *   гарантий (инвариант 5 приложения: вне контура — отдельная зона без кнопки оплаты), `link` — адрес витрины для
 *   человека, который строит адаптер, а не берёт из текста витрины;
 * - `ShopUnavailable` — витрина не ответила или ответила не по схеме: товаров нет, поиск по остальным идёт дальше.
 *   Причина — `detail` (код витрины из перечня, `BAD_RESPONSE`, `NO_RESPONSE`) или `reason` (код агента). Этот
 *   случай **не отбрасывается**: по П38 п. 6 недоступная витрина доходит до человека кодом и причиной.
 */
export type { ShopOffers, ShopUnavailable, ShopUnavailableCause } from "agentic-buyer-ref/src/agent/ports/shop.js";

/**
 * Реестр кодов каталога — **значение** ядра (К17, 32 записи: 22 кода модели и разбора, два сигнала A5, восемь кодов
 * живой проверки). Единственное значение, которое этот модуль ввозит из ядра; всё остальное здесь — типы.
 *
 * Реэкспортируется отсюда, а не ввозится в каждый файл модуля, чтобы у модуля каталога была **одна дверь к ядру**:
 * тогда перечни стража границы проверяются в одном месте, а не в каждом новом файле (К3).
 *
 * Русские тексты человеку живут **в нём**, и второй копии им в `config/` не бывает (Р-1696, приём `src/order/texts.ts`);
 * английских текстов у реестра нет ни у одного кода — у реестров ядра обязателен только `ru` (правило совместимости
 * № 3 ядра), и английскую пару даёт приложение (П38 п. 5, Р-1719).
 */
export { CATALOG_DIAG } from "agentic-buyer-ref/src/agent/catalog/index.js";

/**
 * **Сам порт — тоже тип ядра:** `OfferSource` (`agentic-buyer-ref/src/agent/ports/shop.js`, стадия 2 — выдача по
 * действующему поручению), ровно тот, который отдаёт место сборки (`AgentCore.shops().offers`, `compose.ts`), и
 * ровно тот, который назван в П38 п. 1.
 *
 * Своего интерфейса здесь **нет** — и это исправление **блокера** ревью К1 № 1. Первая редакция объявляла
 * `CatalogCorePort { search(intent: Mandate): Promise<readonly ShopResult[]> }`, то есть заново набирала поля
 * живого `OfferSource`. Копия была бы **совместима по присваиванию** и поэтому никогда бы не покраснела: добавь
 * ядро у `OfferSource` аргумент (срок поиска, сигнал прерывания) или новый исход — приложение осталось бы зелёным
 * со старой формой. Кирпич, который вводился как «своей модели и своих форм нет», завёл бы свою форму для самого
 * порта. Аналогия с `OrderCorePort` (Н-3) здесь не работает: у того свой `OrderRead` из типов контракта
 * приложения, свой параметр `owner` и своя семантика `null` — он не копия ядра.
 *
 * Поручение, которым ищут, — `Mandate` ядра: тот же INTENT, своей копии поручения у приложения нет. Исходы —
 * `ShopOffers | ShopUnavailable`, и своего имени этому объединению приложение не даёт: понадобится оно ВР-2 —
 * заводится **передачей в ядро**, а не здесь (находка ревью К1 № 2).
 *
 * Чего у порта **нет**:
 *
 * 1. **Возврата «только годных товаров».** Отдаётся всё, что ответило ядро, включая исключённые магазины
 *    (`shopIssues` непустой), отклонённые карточки (`dropped`) и недоступные витрины (`ShopUnavailable`): отбор
 *    здесь означал бы, что часть позиций исчезает молча, а это запрещено П38 п. 6.
 * 2. **Решения по товару.** «Показывать или нет», «нужно ли решение человека по A5», «можно ли готовить корзину» —
 *    это `classifyOffer`, `mayDraftCart` и `acceptedA5` ядра (инвариант 2). Порт отдаёт факты, а приложение их
 *    показывает.
 * 3. **Повторов.** Повтор обращения к витрине — дело адаптера ядра (инвариант 9: повтор только при устранении
 *    причины); приложение не перезапрашивает поиск, чтобы «получить ответ получше».
 *
 * `createAgentCore` этот модуль не вызывает: порт подаёт место сборки (Р-1644 — зависимости приходят извне). Иначе
 * модуль каталога знал бы адрес витрин, ключи подписи и журнал ядра.
 */
export type { OfferSource } from "agentic-buyer-ref/src/agent/ports/shop.js";
