// ВР-1, К2 — чтение фактов портом и учёт отклонённого (решение **П38** п. 1 и п. 6 от 22.11.2026).
//
// Что делает модуль: берёт то, что отдал порт ядра (`OfferSource.search`), и раскладывает **каждую** позицию в
// запись учёта. Ничего не отбрасывает и ничего не решает.
//
// Почему учёт вообще нужен. У ядра отклонённое лежит в трёх разных местах, и ни одно из них не похоже на остальные:
// магазин с непустым `shopIssues` исключён **целиком** (товары в `products` при этом есть и выглядят годными),
// карточка, которую адаптер не перевёл, оставляет только код в `dropped` (самой карточки нет вовсе — ни `sku`, ни
// чего-либо ещё), а витрина, не ответившая или ответившая не по схеме, приходит отдельной формой
// `ShopUnavailable`, у которой нет ни товаров, ни фактов. Пройти по `products` и показать их — значит потерять два
// случая из трёх **молча**: человек увидит выдачу, в которой нет половины продавцов, и не узнает, что их не нет, а
// они отклонены. Это ровно то, что П38 п. 6 запрещает.
//
// Чего модуль **не делает**:
//
// 1. **Не решает, показывать ли товар.** «Исключён по модели», «исключён по региону», «доступен с сигналами A5» —
//    это `classifyOffer` ядра, а «можно ли готовить корзину» — `mayDraftCart` (инвариант 2). Здесь товар получает
//    запись с теми кодами, какие дало ядро, и всё.
// 2. **Не схлопывает и не сортирует.** Порядок записей — порядок ответа ядра; одинаковые коды остаются
//    одинаковыми записями (см. оговорку о `dropped` ниже).
// 3. **Не показывает свободный текст.** В записи учёта идут только опознаватели и коды: `merchantId`, `shopId`,
//    `sku`, `CatalogIssueCode`, `A5SignalCode`. Названия, описания и значения атрибутов в учёт **не попадают** — ни
//    в журнал, ни в диагностику, ни в сообщение исключения (находка ревью К2 № 1: первая редакция выгружала в
//    текст исключения весь неразобранный ответ витрины целиком, `JSON.stringify`, и это было единственное место,
//    где текст продавца покидал границу).
//    **`sku` — тоже строка продавца, и ядро её не проверяет:** формат у неё ничем не ограничен, туда можно
//    положить и шестнадцать цифр, поэтому она просеивается фильтром `hasCardNumber` вместе со свободным текстом —
//    кирпич К4 (П38 п. 4). Утверждать, что учёту просев «не нужен вовсе», нельзя (находка ревью К2 № 8).
//    **Где встанет фильтр:** в месте сборки записи **внутри `read`**, а не на экране (хвост ревью К2 № 1,
//    уточнение 22.11.2026): при совпадении запись появляется с кодом и **без значения** `sku` — позиция не
//    теряется, сверка счёта остаётся зелёной.
//    **Почему до К4 это безопасно — условие ревьюера, проверенное, а не обещанное:** записи учёта сегодня не
//    уходят наружу ни одним путём. Единственный читатель `read` — `tests/catalog/read.test.ts`; в `src/` вызова
//    нет (проверяется `grep` по дереву), журнала и диагностики модуль не знает, `node:fs` и сети в нём нет
//    (держит граница модуля, `tests/catalog/boundary.test.ts`), в сообщении исключения полезной нагрузки нет
//    (находка К2 № 1 снята). Единственное место, где значения записи видны, — вывод прогона при падении теста:
//    это консоль прогона, а не журнал, диагностика или файл приложения. Появится в `src/` первый читатель раньше
//    К4 — фильтр переезжает к нему, и это кирпич со своей оценкой, а не перенос.
// 4. **Не повторяет запрос.** Повтор обращения к витрине — дело адаптера ядра (инвариант 9).
// 5. **Не ведёт зону гарантий сам.** Признак контура `inContour` ядра переносится в запись товара как есть — без
//    него К3 не смог бы отделить предложения вне контура, а это инвариант 5 (находка ревью К2 № 3). Адрес витрины
//    для человека (`link`) в учёт не идёт: он нужен **оболочке**, а не записи, и приходит с экранами
//    **ВР-8…ВР-10** — экраны в ВР-1 не входят (П38, «Что меняет»).
//
// **Отказ целиком (fail-closed).** Элемент ответа вне перечня исходов ядра — отказ **всего** чтения: исключение, а
// не «пропустим один и покажем остальное» (инвариант 4 ядра). Уже собранный учёт при этом теряется, и это
// сознательно: ответ, который не разбирается, означает, что форма источника разошлась с типами, и показывать из
// него часть — значит показывать неизвестно что. Что при этом видит человек, решает К3 (находка ревью К2 № 10).
import type { A5SignalCode, CatalogIssueCode, OfferSource, ShopUnavailableCause } from "./port.js";

/**
 * Один исход поиска — **выведенный из порта ядра**, а не набранный здесь руками.
 *
 * Было `readonly (ShopOffers | ShopUnavailable)[]`, и это тот же дефект, что **блокер** ревью К1 № 1: объединение
 * повторялось в приложении, и добавь ядро третий исход — `read` остался бы зелёным со старой формой, а ветвь
 * `never` ниже ничего бы не доказала, потому что сужала бы **свой** список, а не список ядра. С выводом из
 * `OfferSource` третий исход роняет компиляцию именно здесь.
 */
type SearchResult = Awaited<ReturnType<OfferSource["search"]>>[number];

/**
 * Вид записи учёта — **закрытый перечень**, свой; довод, почему своё понятие здесь уместно, — у
 * `CATALOG_ENTRY_KINDS` ниже (в одном месте, а не дважды).
 *
 * - `offer` — товар, который ядро **перевело** в модель К8: `issues` (ошибки модели) и `signals` (сигналы A5) идут
 *   как есть. Пустые оба — товар без замечаний; непустой `issues` — ядро исключит его по модели, но решение это
 *   **его**, не наше;
 * - `dropped` — карточка, которую адаптер **не перевёл** (ответ витрины не по схеме): есть только код. `sku` у неё
 *   нет и быть не может — она не разобрана, и придумывать ей опознаватель нельзя;
 * - `shop_excluded` — магазин исключён **целиком** по ошибкам своих сведений или разбора фида (`shopIssues`). Его
 *   товары в учёт идут тоже, записями `offer`: иначе из учёта исчезло бы, сколько позиций ушло вместе с магазином;
 * - `shop_unavailable` — витрина не ответила, ответила не по схеме или не прошла проверку знака готовности.
 */
const KIND_DECLARED = {
  offer: true,
  dropped: true,
  shop_excluded: true,
  shop_unavailable: true,
} as const satisfies Record<CatalogEntry["kind"], true>;

/**
 * Перечень видов — **понятие приложения, а не копия ядра** (хвост ревью К2 № 2, записано кирпичом К2а).
 *
 * Это сказано здесь нарочно, чтобы перечень не приняли за вторую копию чего-то из ядра и не «починили»,
 * удалив. У ядра понятия «вид записи учёта» **нет**: у него три разные формы (`shopIssues` у фактов магазина,
 * `dropped` списком кодов, `ShopUnavailable` отдельным типом) и ни одного общего имени над ними. Назвать их одним
 * перечнём пришлось именно потому, что в источнике такого перечня не существует, — **Р-1511 не нарушен**: правило
 * запрещает второй перечень **одного** понятия, а не называние своего. Проверка простая: если это понятие
 * появится у ядра, перечень отсюда уходит и остаётся вывод из источника, как у `SearchResult` выше.
 *
 * И **одна форма, а не две** (находка ревью К2 № 5).
 *
 * Первая редакция держала массив строк рядом с литералами `kind` в четырёх интерфейсах, и утверждала, что перечень
 * «закрыт на компиляции». Это было неправдой: связи между массивом и интерфейсами в коде не было, пятый вид в
 * `CatalogEntry` скомпилировался бы без правки массива, а тест сводился к «массив равен своей копии».
 *
 * Теперь перечень **выводится** из объявления, а объявление сверяется с `CatalogEntry` в обе стороны: `satisfies
 * Record<CatalogEntry["kind"], true>` требует **каждый** вид союза (забыли — ошибка «отсутствует свойство») и не
 * допускает лишнего ключа (лишний — ошибка «нет в типе»).
 */
export const CATALOG_ENTRY_KINDS = Object.keys(KIND_DECLARED) as readonly CatalogEntryKind[];

export type CatalogEntryKind = CatalogEntry["kind"];

/** Товар, переведённый в модель: опознаватели и коды ядра. Свободного текста здесь нет (п. 3 шапки). */
export interface OfferEntry {
  readonly kind: "offer";
  readonly merchantId: string;
  readonly sku: string;
  /** зона гарантий витрины — признак ядра как есть (инвариант 5): вне контура платежа нет, человеку ссылка */
  readonly inContour: boolean;
  /** ошибки модели от `validateProduct` ядра плюс ошибки магазина, если он исключён целиком */
  readonly issues: readonly CatalogIssueCode[];
  /** сигналы A5 от `checkProductA5` / `checkShopA5` ядра */
  readonly signals: readonly A5SignalCode[];
}

/** Карточка, которую адаптер не перевёл: только код, опознавателя нет. */
export interface DroppedEntry {
  readonly kind: "dropped";
  readonly merchantId: string;
  readonly code: CatalogIssueCode;
}

/** Магазин исключён целиком. `offers` — сколько его товаров ушло вместе с ним. */
export interface ShopExcludedEntry {
  readonly kind: "shop_excluded";
  readonly merchantId: string;
  readonly codes: readonly CatalogIssueCode[];
  readonly offers: number;
}

/**
 * Витрина недоступна. Причина — форма ядра (`detail` — код витрины из закрытого перечня, `BAD_RESPONSE`,
 * `NO_RESPONSE`; либо `reason` — код агента), своего перечня причин приложение не заводит.
 *
 * Опознавателя может не быть **ни одного**: у ядра необязательны оба — `shopId` отсутствует, когда витрина попала
 * в список по маске и обратиться к ней нельзя, а `merchantId` — когда его не дала сама запись списка. Поэтому в
 * учёт идут **оба**: отбрасывать `shopId`, который ядро дало, значило бы оставлять запись без опознавателя там, где
 * он был (находка ревью К2 № 9; прежний комментарий был пересажен — у ядра оговорка «без id по маске» стоит на
 * `shopId`, а не на `merchantId`).
 */
export interface ShopUnavailableEntry {
  readonly kind: "shop_unavailable";
  readonly shopId: string | undefined;
  readonly merchantId: string | undefined;
  readonly cause: ShopUnavailableCause;
}

export type CatalogEntry = OfferEntry | DroppedEntry | ShopExcludedEntry | ShopUnavailableEntry;

/**
 * Итог чтения: записи и счёт.
 *
 * Счёт — не украшение: он и есть доказательство, что ничего не потеряно. `positions` считается **от ответа ядра**
 * (товары плюс непереведённые карточки по всем витринам), а `entries` — то, что модуль разложил; тест сверяет их
 * между собой, и отбор внутри `read` сделал бы их разными.
 */
export interface CatalogReading {
  readonly entries: readonly CatalogEntry[];
  /** сколько позиций пришло от ядра: `products.length + dropped.length` по всем ответившим витринам */
  readonly positions: number;
  /** витрин, исключённых целиком */
  readonly shopsExcluded: number;
  /** витрин, не ответивших или ответивших не по схеме */
  readonly shopsUnavailable: number;
}

/**
 * Разложить ответ порта в записи учёта.
 *
 * Разбор исходов ядра — **исчерпывающий**, с ветвью `never` (приём П36 дополнения 4): появится у ядра третий исход
 * поиска — здесь перестанет компилироваться, а не тихо пропадёт из учёта. Это та гарантия, которую даёт
 * компиляция, поэтому постоянной фикстуры-поломки на неё не держим — шаг воспроизведения назван в строке кирпича
 * (Р-1702).
 *
 * **Оговорка о `dropped`, важная для слова «на каждую карточку».** Одна запись на карточку — это поведение ядра
 * **у витрин** (`readShop`, Р42 п. 6: коды не схлопываются, запись в журнал на каждую карточку). У фида YML то же
 * поле приходит **схлопнутым** (`readFeed` прогоняет коды через множество, как коннектор ядра), и там число записей
 * `dropped` равно числу **различных** кодов, а не числу карточек. Модуль ничего с этим не делает и не делает вид,
 * что знает число карточек: он раскладывает ровно то, что дало ядро. Для источника ВР-1 — каталога эмулятора витрин
 * — путь именно `readShop`, то есть запись на карточку. Появится фид источником — число позиций у него будет
 * нижней границей, и это придётся сказать человеку словами, а не досчитывать здесь.
 */
export function read(results: readonly SearchResult[]): CatalogReading {
  const entries: CatalogEntry[] = [];
  let positions = 0;
  let shopsExcluded = 0;
  let shopsUnavailable = 0;

  for (const r of results) {
    if ("unavailable" in r) {
      shopsUnavailable += 1;
      entries.push({ kind: "shop_unavailable", shopId: r.shopId, merchantId: r.merchantId, cause: r.unavailable });
      continue;
    }
    if ("facts" in r) {
      const { merchantId, inContour, facts } = r;
      positions += facts.products.length + facts.dropped.length;
      if (facts.shopIssues.length > 0) {
        shopsExcluded += 1;
        entries.push({
          kind: "shop_excluded",
          merchantId,
          codes: [...facts.shopIssues],
          offers: facts.products.length,
        });
      }
      for (const p of facts.products) {
        entries.push({
          kind: "offer",
          merchantId,
          sku: p.product.sku,
          inContour,
          // Ошибки магазина приезжают к каждому его товару: без этого товар исключённого магазина выглядел бы в
          // учёте беспорочным. Сведение — **то же, что у `classifyOffer` ядра**, и это не случайное совпадение, а
          // правило ядра, повторённое здесь формулой. Правило живёт в ядре, поэтому набор кодов записи привязан к
          // источнику **тестом**: он сверяет `issues` с `codes` вердикта `classifyOffer` на тех же фактах, и
          // разойдётся ядро — тест покраснеет (находка ревью К2 № 4). Сам вердикт в учёт не идёт: решение о
          // показе — ядра (инвариант 2).
          issues: [...new Set([...facts.shopIssues, ...p.issues])],
          signals: [...p.signals],
        });
      }
      // Порядок — как у ядра; схлопывания нет (оговорка выше).
      for (const code of facts.dropped) entries.push({ kind: "dropped", merchantId, code });
      continue;
    }
    // Третьего исхода у ядра нет — если появится, компиляция встанет здесь.
    //
    // В сообщении — **только слова**, без полезной нагрузки (находка ревью К2 № 1): `JSON.stringify(rest)` выгрузил
    // бы в текст исключения, а оттуда в журнал и диагностику, весь неразобранный ответ витрины — название,
    // описание, атрибуты, негодный `gtin`. Ветвь срабатывает именно на мусоре от витрины, то есть ровно там, где
    // этого делать нельзя (инвариант 1; то же правило у ядра — `ports/shop.ts`: «сообщение — только код»).
    const rest: never = r;
    void rest;
    throw new Error("исход поиска вне перечня ядра");
  }

  return { entries, positions, shopsExcluded, shopsUnavailable };
}
