// ВР-1, К3 — тексты человеку по кодам каталога (решение **П38** п. 5, **Р-1719** от 22.11.2026).
//
// Правило одно: **русский текст берётся у ядра, английский — наш**.
//
// Почему не пара ru/en целиком в `config/`, как у `sources` или `outcomes` итога: русские строки этих 32 кодов уже
// написаны в реестре `CATALOG_DIAG` (К17), и вторая их копия в файле приложения — это ровно тот дефект, который
// П38 дополнение 1 запрещает: копия **совместима** (строка и строка), разойдётся молча, и человек получит два
// разных объяснения одного кода. Приём не новый — так же сделано у класса проверки клиринга (**Р-1696**,
// `src/order/texts.ts`): в `config/` лежит только `en`, и разбор русскую строку там **не пропускает**.
//
// Поэтому «пары ru/en данными» (Р-1719) исполняется так: пара **собирается** — `ru` из реестра ядра, `en` из
// `config/catalog.default.json`. Данными лежит то, чего у ядра нет.
//
// Перечень кодов приложение не держит: тип и список **выведены** из самого реестра (`keyof typeof CATALOG_DIAG`), и
// разбор требует от файла ровно эти ключи — ни пропуска, ни лишнего, в обе стороны (Р-1511, П38 дополнение 1).
// Оговорка: `CatalogDiagCode` и `CATALOG_DIAG_CODES` у `@kuzin4u/agentic-core` объявлены, но ядро агента их **не
// реэкспортирует**, а подмодуль пакета закрыт стражем границы (П38 п. 2) — отсюда `keyof typeof`. Это не копия:
// ключи берутся у того же объекта, что и тексты.
//
// **Где именно это краснеет** (находка ревью К3 № 1: первая редакция обещала «новый код в реестре ломает
// компиляцию здесь», и это было неправдой — здесь `Record` только строится, а содержимое файла типами не
// проверяется):
//
// - **новый код у ядра без перевода** — ошибка **компиляции**, в тесте: `config/catalog.default.json` ввезён там
//   модулем и сверен `satisfies Record<CatalogDiagCode, { readonly en: string }>`, а `tsc --noEmit` проходит и по
//   `tests` (`include` в `tsconfig.json`). Плюс отказ разбора в прогоне;
// - **лишний или переименованный код в файле** — отказ **разбора** и красный тест ключей файла: `satisfies` лишнего
//   ключа не ловит (проверка лишних свойств работает только на свежем литерале, а ввезённый JSON таким не считается),
//   и обещать здесь компиляцию было бы той же неправдой.
//
// Сам файл в `src/` **не ввозится**: его читает и разбирает вызывающий, потому что набор текстов — настройка
// (инвариант 7), а ввоз модулем вшил бы в сборку именно `catalog.default.json`.
import { CATALOG_DIAG } from "./port.js";
import { obj, slotRe, str } from "../config-parse.js";
import type { UiLang } from "../contract/ui-v1/common.js";

/** Код каталога — **ключ реестра ядра** (коды модели и разбора, сигналы A5, коды живой проверки); своего союза нет. */
export type CatalogDiagCode = keyof typeof CATALOG_DIAG;

/** Все коды реестра. Порядок — как в реестре; перечень нужен разбору и тестам, своего списка в коде нет. */
export const CATALOG_DIAG_CODES = Object.keys(CATALOG_DIAG) as readonly CatalogDiagCode[];

/** Разделы файла `config/catalog.default.json`. */
const SECTIONS = ["codes_en"] as const;

export interface CatalogTexts {
  /** английская пара к текстам реестра ядра (Р-1696): `ru` здесь запрещён и разбором не пропускается */
  readonly codes_en: Readonly<Record<CatalogDiagCode, string>>;
}

/**
 * Разбор `config/catalog.default.json`.
 *
 * Строгость та же, что у разбора текстов итога: лишний раздел — ошибка, лишний код — ошибка, пропущенный код —
 * ошибка, `ru` в файле — ошибка, подстановка в строке — ошибка. Последнее не придирка: у текстов реестра подстановок
 * не бывает ни у ядра (К17 п. 6), ни здесь, и `{money}`, забытый в переводе, доехал бы до человека фигурными
 * скобками.
 */
export function parseCatalogTexts(raw: unknown): CatalogTexts {
  const r = obj(raw, "catalog");
  for (const key of Object.keys(r))
    if (!(SECTIONS as readonly string[]).includes(key)) throw new Error(`catalog.${key}: лишнее поле`);

  const rawEn = obj(r["codes_en"], "catalog.codes_en");
  for (const key of Object.keys(rawEn))
    if (!(CATALOG_DIAG_CODES as readonly string[]).includes(key))
      throw new Error(`catalog.codes_en.${key}: кода нет в реестре ядра`);

  const codes_en = {} as Record<CatalogDiagCode, string>;
  for (const code of CATALOG_DIAG_CODES) {
    const where = `catalog.codes_en.${code}`;
    // Пропущенный код — ошибка здесь: `obj` не найдёт объекта и скажет, какого именно кода нет.
    const one = obj(rawEn[code], where);
    for (const key of Object.keys(one))
      if (key !== "en") throw new Error(`${where}.${key}: русский текст берётся у ядра (Р-1696)`);
    const s = str(one, "en", where);
    for (const m of s.matchAll(slotRe())) throw new Error(`${where}.en: подстановка {${m[1] ?? ""}} здесь не бывает`);
    codes_en[code] = s;
  }

  return { codes_en };
}

/**
 * Текст человеку по коду каталога на языке `lang`.
 *
 * Порядок источников — **реестр раньше файла**, и разбор по языку **исчерпывающий**: у `ru` источник один (реестр,
 * где он обязателен), у `en` — реестр, а если его там нет, наша пара из `config/`. Третий язык роняет компиляцию.
 *
 * `diag` — **параметр**, а не прямое чтение реестра, и это сознательно. У того же приёма в `src/order/texts.ts`
 * ровно эта ветка однажды оказалась **мёртвой**: обещание «язык запроса у реестра берётся раньше» в комментарии
 * было, а до реестра ветка не доходила (находка ревью К2 № 5 Н-3). Проверить её можно только на реестре, у которого
 * нужный язык есть, — значит реестр должен приходить снаружи хотя бы в тесте. По умолчанию — реестр ядра.
 *
 * **Почему разбор по языку, а не общий `human[lang] ?? …`.** Первая редакция была написана так, и поломка это
 * вскрыла: подмена последней строки (`return human.ru` → `return texts.codes_en[code]`) **не покраснела ни на
 * одном тесте**, потому что до неё было не дойти — `human.ru` обязателен, и общая ветка возвращала его раньше.
 * Строка была мёртвой, то есть ровно тем, что эта функция и должна была не допустить. Теперь у каждого языка свой
 * путь, и каждый проверяется.
 */
export function catalogTextOf(
  code: CatalogDiagCode,
  texts: CatalogTexts,
  lang: UiLang,
  diag: typeof CATALOG_DIAG = CATALOG_DIAG,
): string {
  const human = diag[code].human;
  switch (lang) {
    // `ru` у записи реестра **обязателен** (`DiagTexts`), поэтому он и есть источник: своей русской строки нет.
    case "ru":
      return human.ru;
    // Реестр раньше файла: появится `en` у ядра — пойдёт он, и пара из `config/` замолкнет сама.
    case "en":
      return human["en"] ?? texts.codes_en[code];
    // Третий язык роняет компиляцию здесь — и правильно: ему нужно своё решение о том, откуда берутся тексты
    // (у реестра обязателен только `ru`, а в `config/` лежит одна наша пара). Молча отдать английское было бы
    // худшим исходом.
    default: {
      const rest: never = lang;
      void rest;
      throw new Error("язык вне перечня интерфейса");
    }
  }
}
