// Контракт К-Б `/ui/v1` v1.0, § 3 «Общие правила» (КТ-0, К2.1; решение П30, Р-1603): общие формы — деньги, время,
// хэш показанного, провенанс нажатия, действие с объяснением недоступного.
// Только типы и константы: сервера `/ui/v1` и экранов здесь нет — это ИН-0 окна Б, он встаёт на эти типы.
// Деньги берутся типом ядра (`Money` agentic-core через `agentic-buyer-ref`), а не объявляются своей копией: сумма
// в приложении одна и та же величина, что у ядра и Платформы (правило планов № 2, П2 «только через порт»).
import type { CurrencyCode, Money } from "agentic-buyer-ref/src/shared/domain.js";

export type { CurrencyCode, Money };

/** Сумма в ответе экрану — **всегда пара**: целое число минимальных единиц и код ISO 4217 (§ 3 «Деньги»; правило планов
 *  № 2). Отдельного числа без валюты в контракте нет ни в одном поле: у операции ПАО 1.4.0 валюты нет, и её подставляет
 *  сервер из CART покупки — экран пару получает всегда. Тип только замораживает `Money` ядра, полей не добавляет. */
export type UiMoney = Readonly<Money>;

/** Время — UTC в формате ISO 8601 (§ 3 «Время»). Пояс человека экран применяет только для показа. */
export type UiInstant = string;

/** Шаг экрана У1…У7 (§ 4). Сервер отдаёт `step` **вместе** с `state` ядра, чтобы экран не держал таблицу у себя
 *  (правило 3). Таблица «состояние ядра → шаг» — `steps.ts`. */
export const UI_STEPS = ["U1", "U2", "U3", "U4", "U5", "U6", "U7"] as const;

export type UiStep = (typeof UI_STEPS)[number];

/** Язык запроса: `?lang=ru|en`, как у монитора демо-стенда (§ 3 «Тексты»). Текст человеку отдаёт сервер — вместе с кодом;
 *  бренд сервер берёт из конфигурации приложения (инвариант 7, правило планов № 3). */
export type UiLang = "ru" | "en";

/** Карточка, которую человек подтверждает, идёт с `view` (§ 3, правило 1 «Хэш показанного»):
 *  `hash` — SHA-256 канонического JSON ровно того, что экран показывает человеку (поля и тексты, без оформления).
 *  Экран возвращает `shown_hash`, равный `view.hash`; сервер пересчитывает хэш по своей копии `view_id`. Не совпало или
 *  карточка устарела — 409 `SHOWN_STALE` с новой карточкой, и обращения к ПАО нет (закрывает С-07 «подписывают
 *  невиденную корзину»). Считает хэш `showingHash` (`shown-hash.ts`), а не экран. */
export interface UiView {
  readonly view_id: string;
  /** версия текстов карточки, например `u1-card@1.0`: меняется вместе с текстами и входит в хэш */
  readonly text_version: string;
  /** `sha256:<hex>` — канонический JSON показанного. Тип **именованный** (`ShownHash`), а не безымянный `string`:
   *  иначе «хэш показанного» выражен в контракте двумя способами — тот же класс повтора, который убрал К8
   *  (замечание ревью К8 № 6, кирпич К8а). Поведение не меняется: `ShownHash` это `string`. */
  readonly hash: ShownHash;
}

/** **Запись «что человек видел, когда подтверждал»** — пара «хэш показанного + версия текстов» (§ 3, правило 1).
 *  Одна форма на приложение: она **выводится** из `UiView`, а не объявляется второй раз, поэтому типы пары у записи
 *  и у `view` разойтись не могут. До К8 пару объявляли три места — `UiView` здесь, `PrinciplesView` (профиль
 *  принципов) и `ConsentView` онбординга (ИН-П1 окна Б, в `main` ещё не слито); расхождение нашло ревью К2 ИН-П1, и
 *  решение владельца 21.11.2026 (**Р-1682**) свело форму сюда. `ConsentView` переводит окно Б своим кирпичом.
 *  **Что `Pick` даёт и чего не даёт** (находка ревью К8 № 1): наследуются **типы** названных полей, но не состав —
 *  новое поле, добавленное правилом 1 в `UiView`, в `UiShown` само не придёт, его надо назвать здесь же. Довод за
 *  `Pick`, а не `Omit<UiView, "view_id">`: запись показанного — своя роль, и её состав называется явно, а не «всё,
 *  кроме». Вопрос о `Omit` назван владельцу в PR; решение Р-1682 назвало `Pick` буквально, и самовольно форма не
 *  меняется.
 *  Отличие от `UiView`: здесь **нет** `view_id` — он нужен, чтобы сервер **нашёл** свою копию показанного, а в
 *  сохранённой записи искать уже нечего: там лежит то, что подписано. */
export type UiShown = Pick<UiView, "hash" | "text_version">;

/** Хэш показанной карточки, который экран возвращает в теле подтверждения (`view.hash` той карточки). */
export type ShownHash = string;

/** Где нажали: веб, мобильный, MiniApp MAX, модуль ИН-ВМ в приложении банка (§ 3, правило 1).
 *  Перечень **закрытый** и живёт константой, а не только типом: тип в рантайме не существует, и без перечня
 *  `device: "robot"` лёг бы в подписанную версию и в журнал (находка ревью К1.3 № 1). */
export const UI_DEVICES = ["mobile", "web", "max", "bank_module"] as const;

export type UiDevice = (typeof UI_DEVICES)[number];

export const isUiDevice = (s: unknown): s is UiDevice => typeof s === "string" && (UI_DEVICES as readonly string[]).includes(s);

/** Жест подтверждения: `swipe` — подпись жестом (правка 5 канвы), `tap` — нажатие. Перечень закрытый — см. выше. */
export const UI_GESTURES = ["swipe", "tap"] as const;

export type UiGesture = (typeof UI_GESTURES)[number];

export const isUiGesture = (s: unknown): s is UiGesture =>
  typeof s === "string" && (UI_GESTURES as readonly string[]).includes(s);

/** Провенанс нажатия (П26): кто и чем подтвердил. Приходит тем же телом, что `shown_hash`.
 *  `at` — время **по часам устройства**; своё время получения сервер **добавляет**, а не заменяет им время устройства.
 *  Умолчания у провенанса нет (П26): тело без `press` сервер не принимает — как режим прогона тестов не принимает
 *  нажатие без признака «кто нажал». Сервер записывает провенанс в журнал покупки.
 *  `text_version` — версия текстов **показанной карточки**, та же величина, что `view.text_version` (в примере § 3
 *  у обеих `u1-card@1.0`). Расходится — человек подтверждал не те тексты, которые сервер считает показанными. */
export interface UiPress {
  readonly at: UiInstant;
  readonly device: UiDevice;
  readonly text_version: string;
  readonly gesture: UiGesture;
}

/** Кто нажал — признак, который ставит **сервер** по своему знанию (П26). В `UiPress` его нет и быть не может: экран
 *  недоверенная среда (С-12, С-31), и присланное «я человек» ничего не доказывает. Поле живёт в `signed.by` (§ 5.14) —
 *  экран его только показывает.
 *  Перечень **закрытый** и живёт константой, а не только типом: тип в рантайме не существует, а признак уходит в
 *  подписанную версию, в журнал и в акт.
 *  - `human` — нажал человек;
 *  - `emulator` — нажатие в эмуляторе клиента демо-стенда (`DEMO_FAULTS=1`, режим «Авто», П5);
 *  - `test` — подпись делает **прогон тестов**, а не нажатие в эмуляторе интерфейса (**решение владельца 19.11.2026,
 *    22:10**, П26 дополнение 2): П26 требует различать прогон, а акты уходят в НСПК, где «не человек» и «прогон»
 *    читаются по-разному.
 *  **`emulator` и `test` возможны только в режиме прогона тестов** (`DEMO_FAULTS=1`) — как у пульта (П26 п. 2 и п. 6,
 *  П5): вне режима сервер ставит `human`. Здесь это **требование к серверу**, а не проверка: признак приходит
 *  зависимостью (`by` у `SignDeps`), и ставит его сервер `/ui/v1` — ИН-0 окна Б. Тест ограничения живёт там же, где
 *  провайдер; у пульта носитель ограничения — `src/demo/pult-act.ts`, у `/ui` его пока нет (строка в STATUS «Открыто»).
 *  Значения `test` в § 5.14 документа v1.0 нет — войдёт с **К-Б v1.1**, как `notes`, `items[].on` и `locked_id`;
 *  до тех пор перечень сверяется отдельным ожиданием (К2.4).
 *  Страж `isUiSignedBy` нужен **чтению**, а не приёму: им разбирают прежние записи журнала и собирают пометку акта
 *  (ИН-0, § 5.13). **Из тела запроса признак не берётся ни в каком режиме** — тело с полем `by` отклоняется как
 *  неизвестное поле (`signature.ts`), и стража там нет намеренно: экран недоверенная среда (С-12, С-31). */
export const UI_SIGNED_BY = ["human", "emulator", "test"] as const;

export type UiSignedBy = (typeof UI_SIGNED_BY)[number];

export const isUiSignedBy = (s: unknown): s is UiSignedBy =>
  typeof s === "string" && (UI_SIGNED_BY as readonly string[]).includes(s);

/** Действие на экране — вместе с объяснением, **почему недоступно** (§ 3, правило 3 «Экран ничего не считает»): доступность
 *  решает сервер, экран не выводит её сам из состояния и сумм. `why_disabled` — готовый текст человеку; при `enabled`
 *  он `null`. */
export interface UiAction {
  readonly enabled: boolean;
  readonly label: string;
  readonly why_disabled: string | null;
}

/** Строка «что уже сделано и что не списано» (правка 2 канвы): собирает сервер. Экран не складывает суммы и не считает
 *  остаток (правило 3; инвариант 2 — остаток только из `verify` ядра). */
export interface UiDoneLine {
  readonly done: string;
  readonly not_spent: string;
}

/** Строка пояснения с источником и временем проверки: «почему так» выдачи, живая проверка, запись об исполнении.
 *  `source` — откуда сведение (витрина продавца, ваши принципы, запись Платформы), `confirmed` — подтверждено ли
 *  источником. Текст — человеку, код — машине. */
export interface UiLine {
  readonly line: string;
  readonly text: string;
  readonly source: string;
  readonly checked_at: UiInstant;
  readonly confirmed: boolean;
}
