// Контракт К-Б `/ui/v1` v1.0, § 3 «Общие правила» (КТ-0, К2.1; решение П30, Р-1603): общие формы — деньги, время,
// хэш показанного, провенанс нажатия, действие с объяснением недоступного.
// Только типы и константы: сервера `/ui/v1` и экранов здесь нет — это ИН-0 окна Б, он встаёт на эти типы.
// Деньги берутся типом ядра (`Money` agentic-core через `agentic-buyer-ref`), а не объявляются своей копией: сумма
// в приложении одна и та же величина, что у ядра и Платформы (правило планов № 2, П2 «только через порт»).
import type { CurrencyCode, Money } from "agentic-buyer-ref/src/shared/domain.js";

export type { CurrencyCode, Money };

/** Сумма в ответе экрану — **всегда пара**: целое число минимальных единиц и код ISO 4217 (§ 3 «Деньги»; правило планов
 *  № 2). Отдельного числа без валюты в контракте нет ни в одном поле: у операции ПАО 1.4.0 валюты нет, и её подставляет
 *  сервер из CART покупки — экран пару получает всегда. Тип только замораживает `Money` ядра, полей не добавляет. */
export type UiMoney = Readonly<Money>;

/** Время — UTC в формате ISO 8601 (§ 3 «Время»). Пояс человека экран применяет только для показа. */
export type UiInstant = string;

/** Шаг экрана У1…У7 (§ 4). Сервер отдаёт `step` **вместе** с `state` ядра, чтобы экран не держал таблицу у себя
 *  (правило 3). Таблица «состояние ядра → шаг» — `steps.ts`. */
export const UI_STEPS = ["U1", "U2", "U3", "U4", "U5", "U6", "U7"] as const;

export type UiStep = (typeof UI_STEPS)[number];

/** Язык запроса: `?lang=ru|en`, как у монитора демо-стенда (§ 3 «Тексты»). Текст человеку отдаёт сервер — вместе с кодом;
 *  бренд сервер берёт из конфигурации приложения (инвариант 7, правило планов № 3). */
export type UiLang = "ru" | "en";

/** Карточка, которую человек подтверждает, идёт с `view` (§ 3, правило 1 «Хэш показанного»):
 *  `hash` — SHA-256 канонического JSON ровно того, что экран показывает человеку (поля и тексты, без оформления).
 *  Экран возвращает `shown_hash`, равный `view.hash`; сервер пересчитывает хэш по своей копии `view_id`. Не совпало или
 *  карточка устарела — 409 `SHOWN_STALE` с новой карточкой, и обращения к ПАО нет (закрывает С-07 «подписывают
 *  невиденную корзину»). Считает хэш `showingHash` (`shown-hash.ts`), а не экран. */
export interface UiView {
  readonly view_id: string;
  /** версия текстов карточки, например `u1-card@1.0`: меняется вместе с текстами и входит в хэш */
  readonly text_version: string;
  /** `sha256:<hex>` — канонический JSON показанного */
  readonly hash: string;
}

/** Хэш показанной карточки, который экран возвращает в теле подтверждения (`view.hash` той карточки). */
export type ShownHash = string;

/** Где нажали: веб, мобильный, MiniApp MAX, модуль ИН-ВМ в приложении банка (§ 3, правило 1). */
export type UiDevice = "mobile" | "web" | "max" | "bank_module";

/** Жест подтверждения: `swipe` — подпись жестом (правка 5 канвы), `tap` — нажатие. */
export type UiGesture = "swipe" | "tap";

/** Провенанс нажатия (П26): кто и чем подтвердил. Приходит тем же телом, что `shown_hash`.
 *  `at` — время **по часам устройства**; своё время получения сервер **добавляет**, а не заменяет им время устройства.
 *  Умолчания у провенанса нет (П26): тело без `press` сервер не принимает — как режим прогона тестов не принимает
 *  нажатие без признака «кто нажал». Сервер записывает провенанс в журнал покупки. */
export interface UiPress {
  readonly at: UiInstant;
  readonly device: UiDevice;
  readonly text_version: string;
  readonly gesture: UiGesture;
}

/** Действие на экране — вместе с объяснением, **почему недоступно** (§ 3, правило 3 «Экран ничего не считает»): доступность
 *  решает сервер, экран не выводит её сам из состояния и сумм. `why_disabled` — готовый текст человеку; при `enabled`
 *  он `null`. */
export interface UiAction {
  readonly enabled: boolean;
  readonly label: string;
  readonly why_disabled: string | null;
}

/** Строка «что уже сделано и что не списано» (правка 2 канвы): собирает сервер. Экран не складывает суммы и не считает
 *  остаток (правило 3; инвариант 2 — остаток только из `verify` ядра). */
export interface UiDoneLine {
  readonly done: string;
  readonly not_spent: string;
}

/** Строка пояснения с источником и временем проверки: «почему так» выдачи, живая проверка, запись об исполнении.
 *  `source` — откуда сведение (витрина продавца, ваши принципы, запись Платформы), `confirmed` — подтверждено ли
 *  источником. Текст — человеку, код — машине. */
export interface UiLine {
  readonly line: string;
  readonly text: string;
  readonly source: string;
  readonly checked_at: UiInstant;
  readonly confirmed: boolean;
}
