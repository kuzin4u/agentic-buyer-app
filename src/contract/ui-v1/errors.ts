  IDEMPOTENCY_REQUIRED: "same_key",
  /** ПАО 1.4.0: `never` означало бы «повтор не поможет никогда», а здесь повтор **новым** ключом проходит */
  IDEMPOTENCY_CONFLICT: "after_fix",
  /** таблица отказов ядра (`MANDATE_NOT_FOUND`) */
  PURCHASE_NOT_FOUND: "after_human",
