/** Код `/ui` (§ 6). */
export type UiErrorCode = keyof typeof UI_ERROR_STATUS;

/** Перечень кодов `/ui` — порядок § 6 (сверяется тестом К2.4 с таблицей документа). */
export const UI_ERROR_CODES = Object.keys(UI_ERROR_STATUS) as readonly UiErrorCode[];

export const isUiErrorCode = (s: string): s is UiErrorCode => Object.prototype.hasOwnProperty.call(UI_ERROR_STATUS, s);

/**
 * Класс повтора у каждого кода `/ui` — **одна таблица на приложение** (§ 6; решения владельца **Р-1681** и
 * **Р-1685**, П35).
 *
 * До этого кирпича таблиц было **четыре**: `UI_RETRY` сервера (`src/ui-server/errors.ts`), `RETRY_BY_CODE` у
 * поручения и у принципов и временная на один код у знакомства. Расхождение не теоретическое: `IDEMPOTENCY_REQUIRED`
 * однажды разошёлся — у принципов `same_key`, у сервера `after_fix`, — и чинить его пришлось отдельным кирпичом. Класс
 * повтора это **совет человеку**, и неверный совет уехал бы в пилот.
 *
 * С версии **v1.3** класс назван в § 6 документа вместе с источником, поэтому значения здесь не «решены в коде», а
 * **взяты из контракта**, и тест сверяет таблицу с документом построчно. Источник у каждой строки назван тем же
 * словом, что в документе: решение владельца с номером либо таблица ядра или ПАО.
 *
 * Прикладной модуль своей таблицы не держит: он берёт **срез** по кодам, на которые отвечает (`retryFor`). Перечень
 * кодов метода — его собственная норма («какие отказы у меня бывают»), а класс — общая.
 */
