Object.freeze(UI_RETRY);

/**
 * Срез таблицы по кодам, на которые отвечает один метод.
 *
 * Возвращается замороженный объект: прикладной модуль перечисляет **свои** коды, а значения приходят из общей
 * таблицы. Так перечень кодов метода остаётся его нормой, а класс повтора — одной на приложение, и второй копии
 * значений не возникает.
 */
export function retryFor<K extends UiErrorCode>(codes: readonly K[]): Readonly<Record<K, UiRetryClass>> {
  const out = {} as Record<K, UiRetryClass>;
  for (const code of codes) out[code] = UI_RETRY[code];
  return Object.freeze(out);
}

/** Код в ответе об отказе: код `/ui` или код отказа ядра как есть (§ 3 «Ошибки», § 6 последняя строка). */
export type UiFailureCode = UiErrorCode | FailureCode;

/**
 * Сборка тела ошибки — **одна на приложение** (§ 3 «Ошибки»).
 *
 * `uiError` сервера (`src/ui-server/errors.ts`) и отказы прикладных модулей зовут её, а не собирают объект руками:
 * добавится у правила 1 в тело ошибки поле — его получат **все**, а не те, кто вспомнил. Второй сборщик рядом уже
 * заводился и был снят (находка ревью К4 № 4).
 *
 * Статус и класс повтора здесь не подставляются: у кода `/ui` они берутся из `UI_ERROR_STATUS` и `UI_RETRY`, у кода
 * ядра — у ядра, и смешивать эти два пути в одном помощнике значило бы спрятать разницу.
 */
export const uiErrorBody = (
  code: UiFailureCode,
  retry: UiRetryClass,
  text: string,
  view: UiView | null = null,
): UiErrorBody => ({ error: { code, retry, text, view } });

/** Тело ошибки — одно для всех методов (§ 3 «Ошибки»).
 *  `text` предназначен **человеку** и приходит на языке запроса; `view` заполнен, когда сервер выдаёт новую карточку
 *  (`SHOWN_STALE`, `PRICE_CHANGED`), иначе `null`. Сумм, реквизитов и `kid` в теле нет (инвариант 1). */
export interface UiErrorBody {
  readonly error: {
    readonly code: UiFailureCode;
    readonly retry: UiRetryClass;
    readonly text: string;
    readonly view: UiView | null;
  };
}
