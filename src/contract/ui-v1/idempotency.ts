// Контракт К-Б `/ui/v1` v1.0, § 3, правило 2 «Идемпотентность каждого POST» (КТ-0, К2.1; П30).
// Имя заголовка и формат ключа — константой и проверкой, а не литералом по месту вызова: иначе двойное «Подтвердить»
// (С-09) и обрыв связи при оплате (С-18) ловились бы в одном маршруте и не ловились в другом.

/** Имя заголовка ключа идемпотентности — то же, что у ПАО. */
export const IDEMPOTENCY_HEADER = "Idempotency-Key";

/** Ключ генерирует **экран** при первом нажатии и повторяет при повторе того же действия. Формат — UUID v4. */
export type IdempotencyKey = string;

/** UUID v4: версия `4` и вариант `8|9|a|b`, регистр любой. Форму ключа проверяет сервер на входе — ключ не по форме
 *  это `IDEMPOTENCY_REQUIRED`, а не «повтор неизвестного ключа». */
const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export const isIdempotencyKey = (s: string): s is IdempotencyKey => UUID_V4.test(s);

/** Исход проверки повтора — ответы те же, что у ПАО (правило 2):
 *  - `fresh` — ключ впервые, действие выполняется;
 *  - `replay` — тот же ключ и то же тело: отдаётся прежний ответ, **второго действия нет**;
 *  - `conflict` — тот же ключ, другое тело: 409 `IDEMPOTENCY_CONFLICT`;
 *  - `missing` — ключа нет: 400 `IDEMPOTENCY_REQUIRED`.
 *  Ключ экрана и ключ обращения ядра к ПАО — **разные**; ключ ядра сервер выводит из ключа экрана детерминированно,
 *  поэтому повтор экрана это и повтор к ПАО тем же ключом (правило 2). Вывод ключа ядра — у сервера (ИН-0), не здесь. */
export type IdempotencyOutcome = "fresh" | "replay" | "conflict" | "missing";
