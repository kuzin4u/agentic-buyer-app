// Контракт К-Б `/ui/v1` v1.0, § 3, правило 1 «Хэш показанного» (КТ-0, К2.3; П30 дополнение 1, Р-1613).
// Хэш считается **канонизацией ядра** — `canonicalJson` и `sha256Hex` публичного входа `@kuzin4u/agentic-core`, того
// самого модуля, на котором стоит журнал ядра. Своей копии правила канонизации в приложении нет и быть не должно:
// разойдись правило — хэш показанного сошёлся бы у приложения и разошёлся у ядра, и `SHOWN_STALE` срабатывал бы на
// исправных карточках (или, хуже, не срабатывал на подменённых).
// Пакет объявлен **прямой зависимостью** приложения по тегу `#v0.13.1` — тем же, что у ядра агента (П30 доп. 1): опора
// на транзитивную копию держалась бы на подъёме зависимостей, а не на объявлении.
import { canonicalJson, sha256Hex } from "@kuzin4u/agentic-core";
import type { ShownHash, UiView } from "./common.js";

/** Приставка хэша в контракте: `sha256:<hex>` (§ 3, правило 1). */
export const SHOWN_HASH_PREFIX = "sha256:";

/** То, что человек видел: версия текстов и **ровно** показанные поля и тексты карточки, без оформления.
 *  `text_version` входит в хэш: сменились тексты — сменился хэш, и прежнее подтверждение не подходит (иначе человек
 *  подтверждал бы одну формулировку, а сервер принимал бы её за другую). */
export interface ShownPayload {
  readonly text_version: string;
  /** карточка как JSON-значение: объекты, массивы, строки, числа, `true`/`false`, `null` */
  readonly card: unknown;
}

/** Хэш показанной карточки. Канонизация — ключи объектов по алфавиту, без пробелов (`canonicalJson`), поэтому порядок
 *  полей в карточке на хэш не влияет: сервер и экран могут собирать объект в любом порядке.
 *  Значения вне JSON канонизатор не пропускает (`TypeError`: `Date`, `Map`, экземпляр класса, `undefined` в массиве,
 *  `NaN`): время в карточке — уже строка ISO 8601 (§ 3 «Время»), суммы — пара целого и кода валюты. Ошибку наружу не
 *  гасим: карточка с неJSON-значением это дефект сборки ответа, а не случай для 409. */
export function showingHash(shown: ShownPayload): ShownHash {
  return `${SHOWN_HASH_PREFIX}${sha256Hex(canonicalJson({ text_version: shown.text_version, card: shown.card }))}`;
}

/** Форма хэша: приставка и 64 шестнадцатеричных знака в нижнем регистре. Хэш не по форме — не «не совпал», а негодное
 *  тело: сервер отвечает на такое `SHOWN_STALE` с новой карточкой, как и на любой несовпавший (§ 6). */
export function isShownHash(s: string): s is ShownHash {
  return /^sha256:[0-9a-f]{64}$/.test(s);
}

/** Совпал ли хэш, присланный экраном, с хэшем **своей** копии показанного. Сервер пересчитывает хэш сам и ни одного
 *  значения из тела запроса в расчёт не берёт — иначе проверка проверяла бы присланное присланным. */
export function shownMatches(shown: ShownPayload, got: string): boolean {
  return isShownHash(got) && got === showingHash(shown);
}

/** Объект `view` для карточки: идентификатор своей копии, версия текстов и хэш (§ 3, правило 1). */
export function viewOf(viewId: string, shown: ShownPayload): UiView {
  return { view_id: viewId, text_version: shown.text_version, hash: showingHash(shown) };
}
