// Контракт К-Б `/ui/v1` v1.0, § 4 «Состояние покупки — одно на все экраны» (КТ-0, К2.2; П30).
// Таблица «состояние машины ядра → шаг экрана». Держит её **сервер** и отдаёт `step` готовым, чтобы экран не выводил
// шаг сам (правило 3 «Экран ничего не считает»): иначе таблица жила бы в двух местах и разъехалась на первом же новом
// состоянии ядра.
// Перечень состояний берётся у ядра (`PURCHASE_STATES`), а не переписывается: появится у ядра новое состояние —
// таблица перестанет быть полной, и тест К2.2 покраснеет. Тихо выпасть новое состояние не может.
import { PURCHASE_STATES, type PurchaseState } from "agentic-buyer-ref/src/agent/pipeline/machine.js";
import type { UiStep } from "./common.js";

/** Шаг экрана для каждого состояния покупки (§ 4).
 *
 *  Две строки документа названы диапазоном — здесь они разложены по состояниям, и выбор назван словами:
 *  - `INTENT_ACTIVE` — в документе «У2 → У3»: поручение подписано, идёт поиск. Вариантов ещё нет, показывать У3 нечем,
 *    поэтому человек остаётся на **У2** с ответом «поручение подписано, идёт поиск»; У3 наступает с состоянием `OFFERS`.
 *  - `CART_PENDING` — **У4**, `CART_ACTIVE` — **У5** (решение владельца 19.11.2026, развилка **Р-1641**). Прежнее
 *    чтение КТ-0 (оба `CART_*` в У5) **отменено**: § 4 различает У4 «живая проверка» и У5 «корзина», а при обоих
 *    `CART_*` в У5 шаг У4 не достигался **никогда** — то есть один из семи шагов экрана был мёртвым.
 *    По РП35 мандат CART получает `ACTIVE` сразу, поэтому У4 сейчас мелькнёт; шаг станет виден, когда банк начнёт
 *    подписывать CART. Это нормально и названо здесь, чтобы «мелькает» не прочиталось как дефект.
 *  Чтение `INTENT_ACTIVE` как У2 остаётся: вариантов ещё нет, показывать У3 нечем. */
export const STEP_OF_STATE: Readonly<Record<PurchaseState, UiStep>> = {
  /** покупка создана — карточка поручения */
  NEW: "U1",
  /** INTENT запрошен, ждёт подписи человека в банке */
  INTENT_PENDING: "U2",
  /** поручение подписано, идёт поиск (см. оговорку выше) */
  INTENT_ACTIVE: "U2",
  /** выдача готова — две зоны, «почему так», отсев */
  OFFERS: "U3",
  /** CART запрошен, подписи ещё нет — живая проверка (У4, § 5.5) */
  CART_PENDING: "U4",
  /** CART активен (по РП35 сразу `ACTIVE`) — карточка корзины (У5) */
  CART_ACTIVE: "U5",
  /** заказ у продавца создан — оплата */
  ORDERED: "U6",
  /** ждёт решения человека: страница УПК или приложение банка (инвариант 3) */
  CONFIRMING: "U6",
  /** идёт оплата */
  AUTHORIZING: "U6",
  /** операция авторизована, ждём итога расчёта */
  SETTLING: "U7",
  /** итог получен */
  DONE: "U7",
  /** покупка остановлена: код, текст, что дальше */
  STOPPED: "U7",
};

/** Шаг по состоянию. Состояние вне перечня ядра сюда не попадает — его не пропускает тип; на границе `/ui/v1` строку
 *  из запроса сервер сверяет с `PURCHASE_STATES` сам. */
export const stepOfState = (state: PurchaseState): UiStep => STEP_OF_STATE[state];

// Таблицы номеров линии пути здесь **нет намеренно** (решение владельца 22.11.2026, в ответ на находку ревью К2а № 3).
// Кирпич К2а сначала завёл `PATH_N` с числами У2 → 2, У3 → 3, У6 → 6, У7 → 8, выведенными из примеров § 5.2, § 5.4,
// § 5.7 и § 5.8 документа, и это было нарушением Р-1511: сами примеры не источник. По Р-1601 знаменателей два — «из 5»
// для использования и «из 8» для приобретения, — и числа 6 и 8 в линии «из 5» существовать не могут. Источник есть
// только у приобретения (постановка ИН-П1 называет 1, 2 и 3 из 8); сопоставление «У1…У7 → N из 5» лежит в канве
// экранов. Обёртка `path` **снята** из разделов использования выпуском **v1.5** (§ 4, § 5.2, § 5.3, § 5.6, § 5.8;
// Р-1700) и осталась у § 5.17–5.19, где источник чисел есть. Строку линии пути использования экран берёт из словаря
// каркаса; самих строк «Шаг N из 5» в `src/ui-server/shell.ts` и `config/` сегодня нет — это названный пробел § 8 п. 6
// документа, отдельная задача с оценкой.

/** Состояния, которым соответствует данный шаг (для проверок и для сборки экранов окном Б). */
export const statesOfStep = (step: UiStep): readonly PurchaseState[] => PURCHASE_STATES.filter((s) => STEP_OF_STATE[s] === step);
