// Экранирование для страниц демо-стенда — одна функция на весь код страниц (К2.3в, Р-1406 п. 2; закрывает ревью К2.3б № 5 —
// циклический импорт dash-control.ts ↔ server.ts — и ревью К1.4 № 10 — копия в dash.ts). Данные шины на страницы не
// попадают: их выводит скрипт через textContent (инвариант 4); здесь — словари, бренд и параметры конфигурации.

const HTML: Readonly<Record<string, string>> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };

/** Текст для HTML — и в тексте, и в значении атрибута в кавычках: все пять символов `& < > " '`, глобально, за один
 *  проход (`&` первым по смыслу: замена идёт по исходной строке, уже вставленные сущности повторно не трогаются). */
export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => HTML[c]!);
}

/** JSON внутри <script type="application/json">: без «<», чтобы строка данных не закрыла тег. */
export const jsonForScript = (v: unknown): string => JSON.stringify(v).replace(/</g, "\\u003c");
