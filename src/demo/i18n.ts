/** Язык из запроса или окружения: только ru или en, иначе язык по умолчанию. */
export function langOf(v: unknown, fallback: Lang = "ru"): Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v) ? (v as Lang) : fallback;
}

