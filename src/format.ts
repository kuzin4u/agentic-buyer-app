// Показ времени человеку: дата и время до минут по языку запроса (правило планов № 3). Модуль нейтральный — ни
// стенда, ни экранов.
//
// **Показа суммы здесь нет намеренно.** Он уже есть у окна Б — `formatUiMoney` в `src/ui-server/money.ts` (ИН-0, К2,
// ветка `task/in-0`), на той же таблице `src/iso4217.ts`. Вторую копию заводить нельзя: две копии разошлись бы молча,
// и сумма ушла бы на карточку в 100–1000 раз больше (случай IQD — шапка `src/iso4217.ts`). Поэтому строки-пояснения
// карточки (К3) получают показ суммы **портом** `money`, а кто его заполнит — решает чат: вопрос задан в PR #27,
// `src/ui-server/` окно А не импортирует.
import type { UiInstant, UiLang } from "./contract/ui-v1/common.js";

const LOCALE: Readonly<Record<UiLang, string>> = { ru: "ru-RU", en: "en-GB" };

/** Момент времени в текст: дата и время до минут, как на экране мандатов банка стенда (ru «27.11.2026, 12:00»,
 *  en «27/11/2026, 12:00»).
 *  **Пояс — названный** (`timeZone`, имя IANA), а не пояс процесса: текст срока уезжает в строку карточки, входит в
 *  хэш показанного и экраном не переформатируется, поэтому в чужом поясе человек прочитал бы на подписываемой
 *  карточке не тот срок (находка ревью К3 В4). У экрана банка стенда та же задача решена названным `time_zone`
 *  (П2, дополнение 6).
 *  Момент не по форме или неизвестный пояс — исключение: лучше не показать срок, чем показать «Invalid Date» или тот
 *  же срок в чужом поясе. */
export function formatInstant(iso: UiInstant, lang: UiLang, timeZone: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) throw new RangeError(`время не по форме: ${iso}`);
  return d.toLocaleString(LOCALE[lang], {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    timeZone,
  });
}
