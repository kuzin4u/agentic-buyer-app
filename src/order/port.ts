// Н-3, К1 — порт итога покупки (§ 5.8 К-Б; правило планов № 1 «только через порт», инвариант 2 приложения).
//
// Приложение **не обращается к Платформе само** и не держит адаптера ПАО: итог приходит портом уже прочитанным.
// Решение **П36** и решения владельца 21.11.2026 (Р-1690…Р-1693) задают порту пять величин, и ни одну из них
// сборка ответа не добывает и не вычисляет:
//
// 1. **Пара «операция + время чтения»** (Р-1690). Время сверки — это время, когда итог **прочитали у Платформы**, и
//    поставить его может только тот, кто читал. Сборка ответа своего времени не ставит вовсе: `now()` здесь нет и
//    быть не может — это было бы время **показа**, и строка «проверено только что» оказалась бы верна всегда, в том
//    числе на данных суточной давности. По той же причине не годится `Fulfilment.at` (время записи Платформы) и
//    `operation.settled.at` журнала ядра (зависимость от журнала, а не от чтения).
// 2. **Поручение из `verify`** (`UiIntentView`, Р-1692): «не списано» — это **остаток поручения**, а не разница
//    «поручение − списано». Разницу считало бы приложение (инвариант 2, инвариант 6 ядра), и при неполном чтении она
//    разошлась бы с остатком у Платформы.
// 3. **Цена агента** и **ссылка на акт** (Р-1691): в границы Н-3 они не входят — цена агента это модель монетизации
//    М2 (Р-1661), акт — § 5.13. Приложение их не считает и не придумывает: значения подаёт место сборки.
// 4. **Строки словаря каркаса** (`line.not_spent`, `DONE_TEXT`) — портом `ShellText` (Р-1693): они уже есть у окна Б
//    (`src/ui-server/lang.ts`), а своя копия дала бы **два источника одной строки** — ровно то, что убрал К8.
//    Импортировать `src/ui-server/` окно А не может по границе (проверяется `tests/order/boundary.test.ts`).
//
// Операция берётся **типом ядра** (`Operation`), а не своей копией: `fulfilment` в нём уже в валюте CART покупки
// (`fulfilmentIn` ядра), потому что у операции ПАО 1.4.0 валюты нет. Приложение валюту не подставляет.
import type { Operation } from "agentic-buyer-ref/src/shared/domain.js";
import type { UiInstant, UiLang } from "../contract/ui-v1/common.js";
import type { OrderResponse, UiIntentView, UiState, UiStop } from "../contract/ui-v1/methods.js";

/**
 * Что прочитано у Платформы и **когда** (Р-1690).
 *
 * `checked_at` относится к чтению, а не к записи: это момент, в который приложение получило итог. Сравнивать его с
 * `fulfilment.at` не нужно и нельзя — Платформа могла записать исполнение задолго до того, как его прочитали.
 */
export interface OrderRead {
  /** операция с записью об исполнении; `fulfilment` равен `null`, пока расчёта нет (до `SETTLED` — так у ядра) */
  readonly operation: Operation;
  /** время **чтения** у Платформы (момент UTC в форме ISO 8601 — форму держит тот, кто читал) */
  readonly checked_at: UiInstant;
  /** состояние покупки **того же чтения** (находка ревью К1 № 2): без него строку «что уже сделано» можно было бы
   *  вывести из состояния, полученного другим чтением или сигналом потока, и «Оплачено» оказалось бы привязано не к
   *  тому чтению, которым обосновано (П36 п. 1, П31) */
  readonly state: UiState;
  /** исход `verify` поручения: остаток, срок, момент проверки — источник числа «не списано» (Р-1692) */
  readonly intent: UiIntentView;
  /** вердикты по остановке (П28, § 5.8) — их выносит ядро и пульт, экран их только показывает (как в § 5.3) */
  readonly stops: readonly UiStop[];
  /** цена агента — значение места сборки, не вывод приложения (Р-1691, М2) */
  readonly agent_fee: OrderResponse["agent_fee"];
  /** ссылка на карточку акта — значение места сборки (Р-1691, § 5.13) */
  readonly act: OrderResponse["act"];
}

/**
 * Порт ядра для итога.
 *
 * `null` означает «покупки нет **или** она не этого человека»: различать эти два случая приложение не должно — наружу
 * идёт один ответ `PURCHASE_NOT_FOUND` (§ 6), иначе по разнице ответов стало бы видно, что покупка существует и
 * принадлежит другому. Тот же приём, что у порта § 5.3 (`src/ui-server/port.ts`, ИН-0).
 */
export interface OrderCorePort {
  order(purchaseId: string, owner: string): Promise<OrderRead | null>;
}

/**
 * Строки словаря каркаса портом (Р-1693).
 *
 * Обе строки уже есть у окна Б, и заполняет их **он же**: `notSpent` получает сумму парой и сам печатает её по
 * валюте и языку (правило планов № 2), `done` отвечает по состоянию покупки. Приложению итога остаётся взять готовый
 * текст — своей таблицы состояний и своего формата суммы у него нет (правило 3 К-Б).
 */
export interface ShellText {
  /**
   * «Не списано: {money}» словаря каркаса, заполненная **остатком поручения** (Р-1692).
   *
   * Берёт **`verify` целиком**, а не сумму (находка ревью К1 № 3): при `money: UiMoney` в строку прошла бы любая
   * величина, в том числе разница, посчитанная приложением, — тип этого не заметил бы. С `UiIntentView` в строку
   * может попасть только `amount_left` прочитанного `verify`.
   */
  notSpent(intent: UiIntentView, lang: UiLang): string;
  /**
   * «что уже сделано» — `DONE_TEXT` словаря каркаса по состоянию **прочитанного** (находка ревью К1 № 2).
   *
   * Берёт `OrderRead`, а не `UiState`: иначе текст и `checked_at` можно развести и сказать «Оплачено» по состоянию из
   * другого чтения.
   */
  done(read: OrderRead, lang: UiLang): string;
}
