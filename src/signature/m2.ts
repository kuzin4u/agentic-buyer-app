// ИН-П2, кирпич К3 — механика подписи своего агента (**М2**): решение владельца 22.11.2026, **Р-1703**.
//
// Три правила, и все три здесь:
//   1. **Подпись — над хэшем ровно показанного** (правило 1 К-Б v1.5): в версию уходит пара «хэш показанного + версия
//      текстов» общей формы `UiShown`, а не весь `view` и не пересказ карточки своими полями.
//   2. **Версия неизменяема** (приём П32, П34 п. 3): новая подпись прежнюю не стирает и не правит, номер растёт на
//      единицу, хранение — портом, который не умеет ни заменить, ни удалить.
//   3. **Каждую оплату подтверждает человек**: подтверждение годится **ровно для той оплаты, которую человек видел**
//      — для своего человека, своей покупки и своего хэша показанного. Чужая покупка, другой хэш (карточка сменилась,
//      цена поехала) — подтверждения нет, и оплаты нет.
//
// **Способ подписи здесь не выбирается и не назван.** Способ назначает **система**, а не человек на экране
// (**Р-1715**, решение владельца 22.11.2026); мандат подписывается пасскеем (**Р-1714**, решение владельца
// 22.11.2026); пасскей подписывает **хэш показанного как ПЭП приложения**, а мандат на MVP по-прежнему подтверждает
// банк — `sign.where` равен `BANK` (**Р-1716**, вариант А, решение владельца 22.11.2026; Р-1657 и `confirmation.where`
// не меняются). Пасскей над `Mandate.hash` Платформы (вариант Б, путь ПАО 1.5) — отдельная задача после MVP.
// Механика от способа не зависит: она про то, над чем подпись ставится, что о ней записано и когда она годится. По
// чему система назначает способ, приложение **не вычисляет** (инвариант 2). Своего перечня способов (жест / пасскей /
// SMS) здесь **нет** (**Р-1704**, решение владельца 22.11.2026) — где он живёт, решит владелец. Перечень
// `SignatureLevel` ядра не трогается: он про то, какой подпись **оказалась** по ответу Платформы, а не про выбор.
// Номера Р-1714…Р-1716 выданы чатом 22.11.2026; запись — решением **П37** (кирпич К0), до неё адрес у них один —
// постановка ИН-П2 и журнал решений этой задачи.
//
// **Формулировки ПЭП в коде нет** (Р-1703): текст живёт данными в `config/` и правится после юриста без правки кода.
// В версию попадает только **версия текстов** показанного (`shown.text_version`) — по ней видно, под какой
// формулировкой человек подписался; сама формулировка строкой здесь не появляется ни в одном виде.
//
// **Отличия от образца названы, а не умолчаны** (у согласия так же — `consent.ts:7`): пара «хэш + версия текстов»
// названа здесь `shown`, а у согласия то же поле зовётся `view` — имя у формы одно (`UiShown`, Р-1682), и второй
// формы не завелось; в записи журнала стоит вся запись показанного `shown`, а у согласия — только `hash`, потому что
// подпись ПЭП читают по версии формулировки; аналога `allRequiredAccepted` здесь нет — отмечать нечего; и добавлены два
// вопроса, которых у согласия не бывает: «эта оплата подтверждена?» (`approvalFor`) и «подтвердил человек?»
// (`approvedByHuman`).
//
// Чего здесь нет: правил HTTP — ключа идемпотентности, кодов отказа, сверки присланного хэша с копией сервера и
// выдачи `view`. Это методы `/ui/v1` (кирпич К4), и в этой задаче они не делаются. Маршрута `POST /ui/v1/payment` на
// сервере сегодня нет вовсе — механика готова раньше маршрута, и это названо, а не подразумевается.
//
// Приём взят у записи согласия (`src/onboarding/consent.ts`, кирпич К2 ИН-П1) — тот же П32: версии только
// добавляются, ключ по владельцу сессии, журнал пишется последним.
import {
  frozenShown,
  type ShownHash,
  type UiErrorCode,
  type UiInstant,
  type UiPress,
  type UiShown,
  type UiSignedBy,
} from "../contract/ui-v1/index.js";

/** Первый номер версии: нумерация человеческая, с единицы. Своя константа, а не `FIRST_CONSENT_NO` согласия:
 *  нумерации **независимы** — у согласия своя история у каждого человека, здесь своя у каждого человека, и общая
 *  константа связала бы две величины, которые меняются по разным причинам. */
export const FIRST_APPROVAL_NO = 1;

/**
 * Подписанное подтверждение оплаты. **Неизменяемо:** новое подтверждение прежнее не стирает и не правит.
 *
 * `purchase_id` — чью оплату подтвердили. Сумм, реквизитов и номера карты здесь нет (инвариант 1): сумма входит в
 * хэш показанного, и второй её копии в записи не нужно — расходись они, стало бы непонятно, что человек видел.
 * `shown` — хэш показанного и версия текстов (правило 1 К-Б), форма одна на приложение (`UiShown`, Р-1682).
 * `received_at` — время **получения сервером**; время устройства живёт в `press.at` и им не заменяется (П26).
 * `by` — кто нажал; ставит **сервер** по своему знанию, из тела не берётся ни в каком режиме (П26 дополнение 2).
 */
export interface SignedPaymentApproval {
  readonly no: number;
  /** чьё подтверждение — владелец сессии приложения (П34 п. 4) */
  readonly owner: string;
  readonly purchase_id: string;
  readonly shown: UiShown;
  readonly press: UiPress;
  readonly by: UiSignedBy;
  readonly received_at: UiInstant;
}

/**
 * Хранение подтверждений — **портом**, как прочее состояние стенда.
 *
 * Версии только добавляются: `append` не умеет ни заменить, ни удалить, и это свойство **порта**, а не
 * договорённость с тем, кто его вызывает. Отмены подтверждения не существует: человек либо подтвердил эту оплату,
 * либо подтверждает заново — новой версией.
 */
export interface PaymentApprovalStore {
  /** последняя версия этого человека или `null`, если он ещё не подтверждал ничего */
  last(owner: string): SignedPaymentApproval | null;
  /** все версии этого человека по возрастанию номера */
  all(owner: string): readonly SignedPaymentApproval[];
  append(version: SignedPaymentApproval): void;
}

/** Состояние сервера в памяти процесса — как прочее состояние демо-стенда (П2 п. 1–2). Снаружи виден только порт.
 *
 *  Память **по владельцу**: один список на человека. Общий список с отбором по полю дал бы тот же ответ, но
 *  `last(owner)` на нём зависел бы от порядка чужих записей — а он часть правила номера версии. */
export function createPaymentApprovalStore(): PaymentApprovalStore {
  const byOwner = new Map<string, SignedPaymentApproval[]>();
  const listOf = (owner: string): SignedPaymentApproval[] => {
    const was = byOwner.get(owner);
    if (was !== undefined) return was;
    const fresh: SignedPaymentApproval[] = [];
    byOwner.set(owner, fresh);
    return fresh;
  };
  return {
    last: (owner) => byOwner.get(owner)?.at(-1) ?? null,
    all: (owner) => [...(byOwner.get(owner) ?? [])],
    append: (version) => {
      listOf(version.owner).push(version);
    },
  };
}

/**
 * Следующая версия подтверждения. Прежнюю **не трогает**: возвращается новый объект, номер — предыдущий плюс один.
 *
 * Копируются и замораживаются **все слои**, а не только верхний: `shown` и `press`, вставленные ссылкой, остались бы
 * изменяемыми, и тогда у подписанного подтверждения можно было бы задним числом поправить хэш показанного (правило 1)
 * и провенанс нажатия (П26) — то самое, на чём держится «версию нельзя изменить». В П-К1 ровно такую дыру нашло
 * ревью К1.2, в ИН-П1 её закрывали повторно: здесь она закрыта сразу.
 *
 * **Что функция не держит, названо прямо** (находка ревью К3 № 7, то же у образца `consent.ts`): она проверяет, что
 * `prev` принадлежит тому же человеку, но не проверяет, что `prev` — его **последняя** версия. Позови её с `null` у
 * человека, у которого версии есть, и получишь второй номер 1. Поэтому «последнюю» берёт `recordPaymentApproval` у
 * порта (`store.last(owner)`), и прикладной код обязан ходить через него; прямой вызов — для сборки версии из уже
 * прочитанной истории. Заводить здесь второй доступ к хранилищу не стал: это развело бы одну и ту же работу по двум
 * местам. Сузить до «только через запись» — отдельный кирпич с оценкой, если владелец сочтёт нужным.
 */
export function nextApprovalVersion(
  prev: SignedPaymentApproval | null,
  built: {
    readonly owner: string;
    readonly purchase_id: string;
    readonly shown: UiShown;
    readonly press: UiPress;
    readonly by: UiSignedBy;
    readonly received_at: UiInstant;
  },
): SignedPaymentApproval {
  // Номер версии считается по истории **того же** человека, и это держит сама функция, а не её вызывающий (тот же
  // довод, что у согласия): `nextApprovalVersion(store.last("own_1"), { owner: "own_2", … })` дал бы второму человеку
  // номер 2 на его **первом** подтверждении — номер по чужой истории.
  if (prev !== null && prev.owner !== built.owner)
    throw new TypeError(
      `версия подтверждения оплаты: прежняя версия принадлежит ${prev.owner}, а новая — ${built.owner}; номер считается по своему человеку`,
    );
  return Object.freeze({
    no: prev === null ? FIRST_APPROVAL_NO : prev.no + 1,
    owner: built.owner,
    purchase_id: built.purchase_id,
    // Запись показанного копируется **целиком** носителем контракта (`frozenShown`), а не пересобирается по полям:
    // появись у формы `UiShown` новое поле — пересборка теряла бы его молча (замечание ревью К8 № 5, кирпич К8а; так
    // же делают `src/principles/model.ts` и `src/onboarding/service.ts`).
    shown: frozenShown(built.shown),
    // Провенанс — тоже целиком. Носителя вроде `frozenShown` у `UiPress` в контракте нет, и образец (`consent.ts`)
    // пересобирает его по четырём полям `PRESS_KEYS`; здесь взята копия целиком по тому же доводу, что у показанного:
    // новое поле провенанса (П26 его допускает) не должно теряться на записи. Отличие от образца названо здесь.
    press: Object.freeze({ ...built.press }),
    by: built.by,
    received_at: built.received_at,
  });
}

/** Что ищут, когда спрашивают «эта оплата подтверждена?». Все три величины обязательны: человек, покупка и то, что
 *  он видел. Две из трёх — это уже другая оплата.
 *
 *  **Способа оплаты (`mode` § 5.7: `BANK` | `MERCHANT_LINK` | `MERCHANT_QR`) в тройке нет — и это вопрос владельцу,
 *  а не решение** (находка ревью К3 № 4): если способ показан человеку, он входит в хэш показанного и уже учтён;
 *  если нет — подтверждение, данное для оплаты банком, нашлось бы для оплаты по ссылке продавца. Поле не заводится
 *  (домысливать запрещено), вопрос назван в PR и идёт в П37. На стенде расхождение сегодня недостижимо:
 *  `MERCHANT_LINK` и `MERCHANT_QR` отвечают `NOT_ON_STAND`.
 *
 *  **Про имя «М2»:** здесь это **свой агент** — вид агента из § 5.17 (`M1` | `M2` | `M3`), как в постановке
 *  «подпись своего агента (М2)». В § 5.7 той же буквой названы способы оплаты продавцу (`MERCHANT_LINK`,
 *  `MERCHANT_QR`, модель монетизации М2, Р-1661) — это другое понятие, и в этом модуле его нет. Совпадение имён
 *  названо, а не сглажено. */
export interface ApprovalLookup {
  readonly owner: string;
  readonly purchase_id: string;
  readonly shown_hash: ShownHash;
}

/**
 * Подтверждение **ровно этой** оплаты или `null`.
 *
 * Совпасть должны все три величины. Почему не «последнее подтверждение этого человека»: тогда подтверждение одной
 * покупки открыло бы оплату другой, а подтверждение прежней карточки — оплату новой, с другой ценой. Это и есть
 * «каждую оплату подтверждает человек» (Р-1703, инвариант 3): сменилось показанное — человек подтверждает заново.
 *
 * Подтверждение **не расходуется**: законный повтор оплаты по правилу 2 К-Б (двойное нажатие, обрыв связи) — то же
 * действие с тем же телом, и он обязан находить то же подтверждение. Расходуемое подтверждение превратило бы повтор
 * в отказ, а один платёж — в два разных действия.
 *
 * Берётся **последнее** подходящее: человек мог подтвердить одно и то же дважды (повтор с новым ключом), и тогда
 * годится свежая запись, а прежние остаются в истории неизменными.
 */
export function approvalFor(store: PaymentApprovalStore, look: ApprovalLookup): SignedPaymentApproval | null {
  const mine = store.all(look.owner);
  for (let i = mine.length - 1; i >= 0; i--) {
    const v = mine[i]!;
    if (v.purchase_id === look.purchase_id && v.shown.hash === look.shown_hash) return v;
  }
  return null;
}

/**
 * Подтвердил ли **человек**, а не прогон и не эмулятор.
 *
 * Отдельной функцией и без умолчания: инвариант 3 запрещает имитацию подтверждения, а исключение для демо-стенда
 * (`DEMO_FAULTS=1`, П5 и П26 дополнение 2) помечено признаком `by`. Тот, кто решает, годится ли подтверждение для
 * оплаты, обязан задать этот вопрос **явно** — `approvalFor` на него не отвечает, потому что «подтверждение есть» и
 * «подтвердил человек» это разные утверждения, и склеивать их нельзя: в акте для НСПК они читаются по-разному.
 */
export const approvedByHuman = (version: SignedPaymentApproval): boolean => version.by === "human";

/**
 * Запись журнала о подтверждении оплаты. Реквизитов, номера карты и сумм в ней нет (инвариант 1) — номер версии,
 * покупка, запись показанного и провенанс. Формулировки ПЭП в журнале тоже нет: в нём стоит версия текстов.
 *
 * Запись показанного — **одним полем общей формы** `UiShown`, а не парой `hash` + `text_version` рядом (**Р-1682**,
 * решение владельца 21.11.2026). Пара, объявленная здесь во второй раз, и была причиной красного CI на PR #32:
 * сторож «объявление пары в `src/` одно» (тест К2.4) нашёл `src/signature/m2.ts`. Правило сильнее удобства плоской
 * строки журнала: добавь правило 1 К-Б в запись показанного ещё одно поле — править пришлось бы в двух местах, и
 * расхождение было бы тихим.
 */
export interface PaymentApprovedEntry {
  readonly event: "payment.approved";
  readonly version: number;
  readonly owner: string;
  readonly purchase_id: string;
  readonly shown: UiShown;
  readonly press: UiPress;
  readonly by: UiSignedBy;
  readonly received_at: UiInstant;
}

/**
 * Запись журнала об **отказе** подтвердить оплату — пишет её сервис `/ui/v1` (кирпич К4), а не этот модуль.
 *
 * Тип объявлен здесь вместе с портом журнала по той же причине, что у согласия: удача и отказ читаются рядом, одним
 * журналом. Причина (`reason`) экрану не уходит — ему хватает кода и готового текста (правило 3), — но в журнале она
 * нужна: иначе на разборе «человек жаловался, что не смог оплатить» смотреть нечего.
 */
export interface PaymentApprovalRefusedEntry {
  readonly event: "payment.approval_refused";
  readonly owner: string;
  /** код отказа — из **закрытого перечня контракта** (`UiErrorCode`), а не любая строка: иначе в журнал попал бы код,
   *  которого в § 6 нет. Сужение — приём `src/principles/signature.ts` (`SignErrorCode`); у образца `consent.ts`
   *  здесь стоит `string`, и это его унаследованная слабость, а не норма (находка ревью К3 № 9). */
  readonly code: UiErrorCode;
  /** уточнение причины — для разбора, не для экрана */
  readonly reason: string;
  /** покупка из тела, если она была по форме; иначе `null` */
  readonly purchase_id: string | null;
  readonly by: UiSignedBy;
  readonly received_at: UiInstant;
}

export interface PaymentApprovalJournal {
  write(entry: PaymentApprovedEntry): void;
  /** Отказ пишется, когда исход определён, тем же журналом. */
  refused(entry: PaymentApprovalRefusedEntry): void;
}

/** Зависимости записи подтверждения. Каждая — зависимостью, а не значением: время, признак «кто нажал» и хранение
 *  знает тот, кто поднял стенд, а не этот модуль. Форма `by` — та же, что у провенанса сервера
 *  (`src/ui-server/provenance.ts`): `() => UiSignedBy`, умолчания нет ни там, ни здесь. */
export interface RecordApprovalDeps {
  readonly store: PaymentApprovalStore;
  readonly journal: PaymentApprovalJournal;
  /** время получения сервером; время устройства остаётся в `press.at` (П26) */
  readonly now: () => UiInstant;
  /** кто нажал — сервер знает это сам; умолчания нет (П26, П5) */
  readonly by: () => UiSignedBy;
}

/**
 * Записать подтверждение оплаты: новая неизменяемая версия, затем запись журнала.
 *
 * **Порядок именно такой, и он не косметика:** журнал пишется последним, когда исход определён. Запись в журнал перед
 * `append` означала бы строку о подтверждении, которого в хранилище нет, — а журнал читают как доказательство.
 *
 * Тело к этому моменту проверено сервисом `/ui/v1` (К4): хэш показанного совпал с копией сервера (`shownMatches`),
 * **равенство `shown.text_version` и `press.text_version` сверено там же** — расходись они, человек подтверждал не те
 * тексты, и ответ был бы `SHOWN_STALE` (правило 1 К-Б, П26); покупка на своём шаге. Здесь проверяется только то, что нельзя было проверить раньше, — и **исключением**, а не
 * отказом контракта: подтверждение без хэша показанного или без провенанса это дефект сборки ответа, а не случай
 * для 400.
 */
export function recordPaymentApproval(
  deps: RecordApprovalDeps,
  body: {
    readonly owner: string;
    readonly purchase_id: string;
    readonly shown: UiShown;
    readonly press: UiPress;
  },
): SignedPaymentApproval {
  // Подпись над пустым местом ничего не доказывает (правило 1): без хэша показанного версия была бы подписью «под
  // чем-то». Проверяется наличие величины, а не её форма — форму хэша и `view_id` проверяет граница `/ui/v1`.
  if (body.shown.hash === "" || body.shown.text_version === "")
    throw new TypeError("подтверждение оплаты: нет хэша показанного или версии текстов — подписывать нечего (правило 1 К-Б)");
  const received_at = deps.now();
  const by = deps.by();
  const version = nextApprovalVersion(deps.store.last(body.owner), {
    owner: body.owner,
    purchase_id: body.purchase_id,
    shown: body.shown,
    press: body.press,
    by,
    received_at,
  });
  deps.store.append(version);
  deps.journal.write({
    event: "payment.approved",
    version: version.no,
    owner: version.owner,
    purchase_id: version.purchase_id,
    // Та же замороженная запись, что в версии: журнал и версия говорят об одном показанном, а не о двух похожих.
    shown: version.shown,
    press: version.press,
    by,
    received_at,
  });
  return version;
}
