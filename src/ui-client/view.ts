// Логика каркаса, вынесенная из разметки (ИН-0, кирпич К4).
//
// Зачем отдельным модулем: в `.svelte` эту логику нечем закрыть тестом — смонтировать собранный компонент в
// рукописном подменённом DOM (`tests/support/fake-dom.ts`) нельзя, а новая зависимость для рендера в тестах это
// решение владельца, а не выбор окна Б (вопрос задан в отчёте по К4 в PR #26). Вынесенная сюда, логика проверяется
// прямо, а в `App.svelte` остаются разметка и состояние.
//
// Ничего, кроме выбора готовых строк и порядка чтений, здесь нет (правило 3 К-Б «Экран ничего не считает»): ни суммы,
// ни шага, ни доступности действия этот модуль не выводит.
import type { UiPress } from "../contract/ui-v1/index.js";
import type { ShellData } from "../ui-server/shell.js";
import type { ReadFail, ReadFailPlain, UiFailure } from "./api.js";

/**
 * Порядок чтений: применяется ответ **последнего** чтения.
 *
 * Чтение покупки запускают четыре повода (сигнал потока, возврат потока, «Обновить», «Повторить»), и они
 * накладываются. Ответ более старого чтения, пришедший последним, перезаписал бы показанное более ранним состоянием —
 * вплоть до откатa с итогового шага на предыдущий (находка ревью К3б № 1). Это прямо против правила 4: показывается
 * то, что прочитано, и именно **последнее** прочитанное.
 */
export interface Latest {
  /** Выполнить чтение; `null` — ответ обогнало более новое чтение, применять его нельзя. */
  run<T>(read: () => Promise<T>): Promise<T | null>;
  /** Идёт ли чтение прямо сейчас: второго поверх идущего не запускаем. */
  readonly busy: boolean;
}

export function latest(): Latest {
  let generation = 0;
  let pending = 0;
  return {
    async run<T>(read: () => Promise<T>): Promise<T | null> {
      const mine = ++generation;
      pending += 1;
      try {
        const value = await read();
        return mine === generation ? value : null;
      } finally {
        pending -= 1;
      }
    },
    get busy(): boolean {
      return pending > 0;
    },
  };
}

/** Раздел ли это пути (У8–У10), а не шаг покупки. Перечни — с сервера, своих у экрана нет. */
export const isPlace = (shell: ShellData | null, id: string | null): boolean =>
  id !== null && shell !== null && shell.places.some((p) => p.id === id);

/** Подпись раздела по опознавателю — из перечней сервера. Опознавателя в перечнях нет (сервер и экран разошлись
 *  версиями) — показывается сам опознаватель, а не пустой заголовок (находка ревью К3 № 13). */
export const labelOf = (shell: ShellData | null, id: string | null): string => {
  if (id === null) return "";
  if (shell === null) return id;
  return [...shell.steps, ...shell.places].find((x) => x.id === id)?.label ?? id;
};

/** Строка о неудаче **до словаря** — из трёх строк, положенных на страницу сервером. Причины не смешиваются: «нет
 *  связи», «вход не выполнен» и «сбой на нашей стороне» это разные случаи (находки ревью К3 № 2 и К3а № 1). */
export const bootLine = (boot: Readonly<Record<string, string>>, fail: ReadFailPlain): string =>
  fail.reason === "offline" ? boot["state.offline"]! : fail.reason === "no_session" ? boot["state.session_gone"]! : boot["state.broken"]!;

/** Та же строка **из словаря**, когда он уже доехал. Отказ по контракту сюда не попадает: у него своё тело § 3. */
export const failLine = (shell: ShellData, fail: ReadFailPlain): string =>
  fail.reason === "offline" ? shell.text["state.offline"] : fail.reason === "no_session" ? shell.text["state.session_gone"] : shell.text["state.broken"];

/** «Что делать» по классу повтора. Класса нет в перечне сервера (ядро добавило новый) — показывается сам класс, а не
 *  пустое место (находка ревью К3а № 6). */
export const retryLine = (shell: ShellData, failure: UiFailure): string =>
  (shell.retry as Readonly<Record<string, string>>)[failure.retry] ?? failure.retry;

/** Можно ли повторить **то же чтение** на месте. Только `same_key`: при `after_fix` и `after_human` повтор расходился
 *  бы с подписью действия, а при `never` не помог бы никогда (находка ревью К3 № 8). */
export const canRetryInPlace = (failure: UiFailure): boolean => failure.retry === "same_key";

/** Нужен ли выход через страницу, а не повтор чтения: сессию выдаёт раздача каркаса, и повтор того же запроса
 *  крутился бы без выхода (находка ревью К3а № 1). */
export const needsPage = (fail: ReadFail): boolean => fail.reason === "no_session";

/**
 * Пометка «подписывает не человек» (кирпич К6; П26, П5 п. 3).
 *
 * `null` — подписывает человек, и пометки нет: лишняя пометка у обычного человека обесценила бы её там, где она
 * важна. Строку выбирает **не экран по смыслу**, а словарь по признаку, который поставил сервер: своих слов о том,
 * кто нажал, у экрана нет (правило 3). Признак, которого экран не знает, пометки не даёт — врать про него нельзя.
 */
export const signedByLine = (shell: ShellData): string | null => {
  // Условие **от человека**, а не перечнем не-человеческих значений: у контракта перечень закрытый, но он растёт
  // (`test` появился решением владельца 19.11), и перечисление поимённо однажды потеряло бы пометку молча — это была
  // находка ревью К5 № 3. Теперь незнакомое значение даёт общую пометку «подписано не вами», а не пустоту.
  if (shell.signed_by === "human") return null;
  if (shell.signed_by === "test") return shell.text["signed.test"];
  if (shell.signed_by === "emulator") return shell.text["signed.emulator"];
  return shell.text["signed.other"];
};

/**
 * Можно ли нажать «Принять условия» (экран П3, кирпич К5).
 *
 * Это **единственная** мерка, которую экран П3 делает сам, и она разрешена прямо: сервер отдаёт перечень
 * обязательных пунктов и готовый текст причины, а экран сверяет, все ли обязательные отмечены (постановка ИН-П1,
 * § 5.18). Окончательно решает § 5.19 — он один знает, что пришло в теле, и отвечает `CONSENT_INVALID`, если
 * отмечено не всё.
 *
 * Чего здесь нет: **своего перечня обязательных**. Обязательность приходит полем `required` каждого пункта, и
 * выдумать её экран не может (правило 3, инвариант 2). Пустой перечень пунктов не делает кнопку доступной:
 * «обязательных нет» это не «со всем согласен», а карточка, которую сервер собрал неверно.
 */
export const canAccept = (
  consents: readonly { readonly id: string; readonly required: boolean }[],
  ticked: ReadonlySet<string>,
): boolean => {
  const required = consents.filter((c) => c.required);
  return required.length > 0 && required.every((c) => ticked.has(c.id));
};

/**
 * Повтор **последнего** обращения (кирпич К5а по находке ревью К5 № 1).
 *
 * Прежде кнопка «Повторить» всегда звала чтение покупки. На пути знакомства покупки нет, чтение сразу возвращалось,
 * и кнопка не делала **ничего**: человек, у которого оборвалась связь на П1 или П3, оставался на экране без выхода —
 * вернуть экраны можно было только перезагрузкой страницы. Один слот «последней неудачи» на пять разных обращений и
 * был корнем: экран знал, что не получилось, но не знал, **что повторять**.
 *
 * Поэтому «что повторять» хранится рядом с «что не получилось». Вынесено сюда, а не оставлено в разметке, по тому же
 * доводу, по которому в К4а ИН-0 переехали правила «когда перечитывать»: в `.svelte` это ничем не держится, и
 * блокеры остаются зелёными (находка ревью К4 № 5 ИН-0).
 */
export interface Retry {
  /** Запомнить обращение как последнее. */
  set(run: () => Promise<void>): void;
  /** Повторить последнее; если его нет — ничего не делать. */
  run(): Promise<void>;
  /** Есть ли что повторять: у кнопки должна быть причина существовать. */
  readonly has: boolean;
}

export function retry(): Retry {
  let last: (() => Promise<void>) | null = null;
  return {
    set: (run) => {
      last = run;
    },
    run: async () => {
      // Повторяется **то же** обращение, а не «обычно покупка»: на знакомстве это чтение § 5.17 или § 5.18, при
      // приёме условий — тот же POST с тем же ключом.
      if (last !== null) await last();
    },
    get has(): boolean {
      return last !== null;
    },
  };
}

/**
 * Ключ повтора для приёма условий (кирпич К5а по находке ревью К5 № 3).
 *
 * Правило 2 требует двух вещей сразу, и прежде держалась только одна:
 * - **повтор того же нажатия идёт тем же ключом** — иначе обрыв связи превратился бы в два согласия;
 * - **другое действие идёт своим ключом** — иначе сервер ответит `IDEMPOTENCY_CONFLICT`, и это тупик: класс
 *   `after_fix` кнопки повтора не даёт, а ключ не менялся нигде, кроме `SHOWN_STALE`. Разобранный случай: отметил
 *   оба пункта, нажал, связь оборвалась, отметил ещё один пункт, нажал — конфликт навсегда.
 *
 * Поэтому ключ привязан к **набору отметок**: пока он тот же, ключ тот же; изменился — ключ новый. Сброс нужен ещё в
 * двух случаях, и оба названы у вызывающего: новая карточка (`SHOWN_STALE`) и конфликт ключа.
 */
/** Попытка приёма условий: ключ повтора и провенанс нажатия. Оба живут **вместе**, пока действие то же. */
export interface AcceptAttempt {
  readonly key: string;
  readonly press: UiPress;
}

export interface AcceptKeys {
  /** Ключ и провенанс для этого действия. Те же, пока подпись действия не изменилась. */
  for(signature: string): AcceptAttempt;
  /** Забыть: следующее нажатие получит новый ключ и новый провенанс. */
  reset(): void;
}

/**
 * Ключ **и провенанс** запоминаются вместе — иначе повтор посылал бы другое тело.
 *
 * Сервер считает отпечаток по **всему** телу, включая `press.at`. Значит нельзя отдать тот же ключ с новым временем
 * нажатия: это другое тело при том же ключе, то есть `IDEMPOTENCY_CONFLICT`. Пока действие то же, тело обязано быть
 * тем же — и ключ, и время нажатия берутся из одной запомненной попытки (находка второго прохода ревью К5 № 9).
 *
 * Подпись действия задаёт вызывающий: это выбранный вид агента, набор отмеченных пунктов и хэш показанного — всё,
 * что делает действие собой. Время нажатия в подпись **не входит**: два нажатия с одним выбором это одно действие,
 * и повтор обязан быть повтором, а не вторым согласием.
 */
export function acceptKeys(newKey: () => string, newPress: () => UiPress): AcceptKeys {
  let attempt: AcceptAttempt | null = null;
  let signature: string | null = null;
  return {
    for: (next) => {
      if (attempt === null || signature !== next) {
        attempt = { key: newKey(), press: newPress() };
        signature = next;
      }
      return attempt;
    },
    reset: () => {
      attempt = null;
      signature = null;
    },
  };
}

/** Строка шага пути — **из словаря сервера** с подстановкой чисел (находка ревью К5 № 8). Своего формата «1 / 8» у
 *  экрана нет: без слова он не читается, и парности ru/en у него не было бы. Подстановка — одним местом, а не тремя
 *  копиями по разметке. */
export const pathLine = (shell: ShellData, path: { readonly n: number; readonly of: number }): string =>
  shell.text["path.step"].replace("{n}", String(path.n)).replace("{of}", String(path.of));

/**
 * Поводы перечитать покупку — одним местом.
 *
 * Было в разметке, и там это ничем не держалось: убери `!busy` из `App.svelte` — все тесты оставались бы зелёными, а
 * два запроса на одно «Обновить» вернулись бы (находка ревью К4 № 5). Правил здесь ровно три, и каждое названо:
 * - **сигнал потока** — перечитывать только **свою** покупку: по чужому опознавателю читать нечего;
 * - **возврат потока** — перечитать, потому что пока он молчал, покупка могла измениться (правило 4), но не поверх
 *   уже идущего чтения: `open` наступает сразу после открытия потока;
 * - **«Обновить»** — перечитать и поднять поток заново **только если он закрыт**: живой поток рвать незачем, при
 *   временном обрыве браузер восстановит его сам.
 */
export interface ReadTriggers {
  signal(purchaseId: string): void;
  back(): void;
  refresh(): Promise<void>;
}

export function triggers(o: {
  readonly purchaseId: string | null;
  readonly hasPurchase: () => boolean;
  readonly feedClosed: () => boolean;
  readonly busy: () => boolean;
  readonly read: () => Promise<void>;
  readonly listen: () => void;
}): ReadTriggers {
  return {
    signal: (purchaseId) => {
      if (purchaseId === o.purchaseId) void o.read();
    },
    back: () => {
      if (o.hasPurchase() && !o.busy()) void o.read();
    },
    refresh: async () => {
      await o.read();
      if (o.feedClosed()) o.listen();
    },
  };
}
