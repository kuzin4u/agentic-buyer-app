// Строки, которые нужны экрану **до** словаря (ИН-0, подшаг К3б; находки ревью К3 № 1 и К3а № 4).
//
// Пока `GET /ui/shell` не доехал, сказать «нет связи», «сбой», «вход не выполнен» и «повторить» больше нечем: своего
// словаря у экрана нет и быть не должно (правило 3 К-Б). Сервер кладёт эти строки атрибутами точки монтирования, а
// экран их читает — и **имена атрибутов живут одной копией здесь**: двумя копиями (сервер складывает из ключей,
// клиент читает литералы `dataset`) расхождение превращалось бы в пустое сообщение и кнопку без подписи, то есть
// снова в неработающий экран, и ничем, кроме совпадения, пара не держалась бы (находка ревью К3а № 4).
//
// Модуль нарочно **без зависимостей**: его импортируют и сервер (`shell.ts`), и собранный экран (`api.ts`), поэтому
// ни `node:*`, ни DOM здесь появиться не могут — иначе в сборку каркаса потянулся бы серверный код.

/** Ключи словаря `SHELL_TEXT`, которые уходят на страницу. Перечень закрытый: добавилась строка — добавилась и пара
 *  «ключ → атрибут», а не литерал по месту. */
export const BOOT_KEYS = ["state.offline", "state.broken", "state.no_session", "action.retry", "action.reopen"] as const;

export type BootKey = (typeof BOOT_KEYS)[number];

/** Имя атрибута разметки: `state.no_session` → `data-state-no-session`. */
export const bootAttr = (key: BootKey): string => `data-${key.replace(/[._]/g, "-")}`;

/** Имя того же атрибута в `dataset` браузера: `state.no_session` → `stateNoSession`. Правило перевода то же, что у
 *  браузера (дефис и следующая буква → заглавная), и выведено из `bootAttr`, а не записано рядом второй копией. */
export const bootDatasetKey = (key: BootKey): string =>
  bootAttr(key)
    .slice("data-".length)
    .replace(/-([a-z])/g, (_whole, letter: string) => letter.toUpperCase());
