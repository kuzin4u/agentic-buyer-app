// `GET /ui/v1/feed` — поток событий (ИН-0, К2; контракт К-Б § 5.9, правило 4 «поток — только сигнал»).
//
// Событие говорит ровно одно: «что-то изменилось». Ни статуса, ни суммы, ни итога в нём нет — получив событие, экран
// перечитывает `GET /ui/v1/purchase/{id}` или `GET /ui/v1/order/{id}` и показывает **только прочитанное** (инвариант 6
// приложения в редакции П31: до ПАО 1.5.0 события Платформы не подписаны).
// Поэтому в строку SSE уходит не объект источника, а **собранный заново** из четырёх полей: передай сюда ядро событие с
// лишним полем — оно до экрана не доедет, и «Оплачено» по событию нарисовать будет нечем.
import type { UiFeedEvent } from "../contract/ui-v1/index.js";

/** Имя события SSE (§ 5.9: `event: purchase`). */
export const UI_FEED_EVENT = "purchase";

/** Четыре поля сигнала — и ничего больше. Пересборка объекта и есть та самая проверка: лишнее поле отсекается здесь,
 *  а не надеждой на дисциплину источника. */
export const feedSignal = (e: UiFeedEvent): UiFeedEvent => ({
  event_id: e.event_id,
  purchase_id: e.purchase_id,
  kind: e.kind,
  at: e.at,
});

/** Строка SSE для одного сигнала. `id:` — тот же `event_id`: доставка «не менее одного раза», и экран отбрасывает
 *  повтор по нему же. */
export const feedChunk = (e: UiFeedEvent): string =>
  `id: ${e.event_id}\nevent: ${UI_FEED_EVENT}\ndata: ${JSON.stringify(feedSignal(e))}\n\n`;
