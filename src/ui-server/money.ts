// Формат суммы в текстах сервера `/ui/v1` (ИН-0, К2; контракт К-Б § 3 «Деньги», правило планов № 2).
//
// Сам показ суммы живёт в нейтральном `src/money.ts` (кирпич К4а, решение владельца **Р-1667**): его нужно и окну А
// для порта `MoneyText` в П-К4, а импортировать из `src/ui-server/` оно не может по границе. Здесь остаётся только
// привязка к типам контракта — чтобы маршруты `/ui/v1` звали показ суммы с `UiMoney` и `UiLang`, а не с «чем-нибудь
// похожим». Второй функции показа суммы в приложении нет и быть не должно: одна величина печаталась бы в двух местах
// по-разному.
//
// В ответах экрану сумма идёт **парой** `{ amount, currency }` как есть из ядра — пару экран получает всегда. Текст
// человеку («Не списано: 6 320,00 ₽») собирает сервер: формат зависит от валюты и языка, знак валюты литералом не
// пишется. Экран сумм не складывает и не пересчитывает (правило 3).
import { formatMoneyText } from "../money.js";
import type { UiLang, UiMoney } from "../contract/ui-v1/index.js";

/** Сумма человеку на языке ответа. Валюта вне таблицы ISO 4217 и нецелое число минимальных единиц — исключение, а не
 *  тихий показ с неверным масштабом (см. `src/money.ts`). */
export const formatUiMoney = (m: UiMoney, lang: UiLang): string => formatMoneyText(m, lang);
