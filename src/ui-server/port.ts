// Порт к ядру для сервера `/ui/v1` (ИН-0, К2; правило планов № 1 «только через порт», инвариант 2 приложения).
//
// Сервер не обращается ни к Платформе, ни к продавцам и не держит адаптера ПАО: он получает от ядра **готовые** решения
// и величины и только перекладывает их в типы контракта. Остаток поручения, его срок и момент проверки — исход
// `GET /pao/v1/mandates/{id}/verify` ядра (§ 5.3): приложение их не считает и не кэширует (инвариант 2).
// Доступность «Стоп» тоже приходит от ядра: вывести её «из состояния» значило бы завести у приложения своё правило
// рядом с правилом ядра (правило 3 К-Б).
import type { UiFeedEvent, UiIntentView, UiState, UiStop } from "../contract/ui-v1/index.js";

/** Состояние покупки, как его отдаёт ядро. Поля — ровно те, из которых собирается ответ § 5.3; ни реквизитов, ни `kid`,
 *  ни криптограммы здесь нет и быть не может (инвариант 1). */
export interface CorePurchase {
  readonly purchase_id: string;
  /** состояние машины ядра: шаг экрана выводится из него таблицей КТ-0, а не приходит от ядра */
  readonly state: UiState;
  /** исход `verify` поручения: идентификатор, статус, остаток, срок, момент проверки, номер распоряжения об отзыве */
  readonly intent: UiIntentView;
  /** вердикты по остановке (П28, § 5.9) — их выносит ядро и пульт, экран их только показывает */
  readonly stops: readonly UiStop[];
  /** можно ли остановить покупку прямо сейчас — решение ядра, не вывод приложения */
  readonly stoppable: boolean;
}

/**
 * Порт ядра.
 *
 * `purchase` — чтение состояния: `null` означает «покупки нет **или** она не этого человека». Различать эти два случая
 * сервер не должен: наружу идёт один ответ `PURCHASE_NOT_FOUND` (§ 6), иначе по разнице ответов стало бы видно, что
 * покупка существует и принадлежит другому.
 *
 * `subscribe` — сигналы для потока § 5.9 **этого** владельца. Поток только сигнал (правило 4): событие говорит
 * «что-то изменилось», и статусов, сумм и итогов в нём нет. Владелец в подписке обязателен (находка ревью К2 № 5):
 * поток по всем покупкам выдавал бы чужие `purchase_id`, и по нему стало бы видно то, что скрывает единый
 * `PURCHASE_NOT_FOUND`. Отбор — у ядра или у порта, не у экрана. Возвращается отписка.
 */
export interface UiCorePort {
  purchase(purchaseId: string, owner: string): Promise<CorePurchase | null>;
  subscribe(owner: string, listener: (event: UiFeedEvent) => void): () => void;
}
