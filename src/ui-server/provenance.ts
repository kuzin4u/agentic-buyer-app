// Признак «кто нажал» у сервера `/ui/v1` (ИН-0, кирпич К5; **П26** и его **дополнение 2**, решение владельца
// 20.11.2026 — Р-1648).
//
// Признак ставит **сервер** по своему знанию, и это главное правило: экран — недоверенная среда (С-12, С-31), и
// присланное им «я человек» ничего не доказывает. Отсюда три следствия, каждое проверяется тестом рядом:
//
// 1. **Вне режима прогона тестов сервер ставит `human`** — всегда и без вариантов.
// 2. **`emulator` и `test` возможны только при `DEMO_FAULTS=1`** (как у пульта, П26 п. 2 и п. 6, П5), и в этом режиме
//    признак **обязателен**: умолчания нет. Отсутствие провайдера в режиме прогона — ошибка сборки сервера, а не
//    «подставим `human`»: молчаливое умолчание записало бы прогон человеком, и в акте появилось бы ложное «да»
//    (разобранный случай пульта — расхождение № 15).
// 3. **Из тела запроса признак не берётся ни в каком режиме.** Тело с полем `by` отклоняется как неизвестное поле —
//    не «игнорируется», потому что молча выброшенное поле выглядит для отправителя принятым.
//
// Перечень значений **не объявляется здесь второй копией**: он живёт в контракте (`UI_SIGNED_BY`, КТ-0, кирпич К0а
// окна А). Вторая копия перечня — ровно то, что К0а убрал.
import { isUiSignedBy, type UiSignedBy } from "../contract/ui-v1/index.js";

export interface ProvenanceOptions {
  /** Режим прогона тестов демо-стенда (`DEMO_FAULTS=1`, П5). */
  readonly faults: boolean;
  /**
   * Кто нажал — **в режиме прогона тестов**. Обязателен при `faults: true` и не принимается вне режима.
   *
   * Зависимостью, а не значением: кто нажал, знает тот, кто поднял стенд, а не маршрут. Вне режима передавать его
   * бессмысленно и опасно — это была бы попытка пометить подпись не человеком там, где никакого прогона нет.
   */
  readonly by?: () => UiSignedBy;
}

/** Признак «кто нажал» для одного действия. */
export type Provenance = () => UiSignedBy;

/**
 * Собрать источник признака. Ошибки сборки — исключения **при старте**, а не отказы на запросе: сервер с негодной
 * настройкой провенанса не должен подниматься вовсе.
 */
export function createProvenance(o: ProvenanceOptions): Provenance {
  if (!o.faults) {
    if (o.by !== undefined) {
      throw new TypeError("провенанс /ui/v1: вне режима прогона тестов признак «кто нажал» не принимается — сервер ставит human (П26)");
    }
    return () => "human";
  }
  const by = o.by;
  if (by === undefined) {
    throw new TypeError("провенанс /ui/v1: в режиме прогона тестов признак «кто нажал» обязателен, умолчания нет (П26 доп. 2)");
  }
  return () => {
    const got = by();
    // Негодное значение провайдера — тоже исключение, а не `human`: иначе опечатка в сборке стенда превратила бы
    // прогон в человека.
    if (!isUiSignedBy(got)) throw new TypeError(`провенанс /ui/v1: негодный признак «кто нажал»: ${String(got)}`);
    return got;
  };
}

/** Глубина обхода тела: провенанс лежит на первом-втором уровне (`press.by`), но искать его надо не по месту, а по
 *  имени — иначе хватило бы завернуть поле в лишний объект. Предел нужен, чтобы ссылающаяся на себя структура не
 *  зацикливала проверку. */
const MAX_DEPTH = 6;

/**
 * Есть ли в теле запроса поле `by` — то есть попытка экрана сказать, кто нажал.
 *
 * Проверяется **всё** тело, а не только ожидаемое место: поле `by` не бывает законным ни у одного метода `/ui/v1`
 * (в ответах признак приходит в `signed.by`, его ставит сервер), поэтому его появление где угодно — негодное тело.
 */
export function claimsSignedBy(body: unknown, depth = 0): boolean {
  if (depth > MAX_DEPTH || body === null || typeof body !== "object") return false;
  if (Array.isArray(body)) return body.some((item) => claimsSignedBy(item, depth + 1));
  if (Object.prototype.hasOwnProperty.call(body, "by")) return true;
  return Object.values(body).some((value) => claimsSignedBy(value, depth + 1));
}
