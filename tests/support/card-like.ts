// Х3 (П-9.3 — П-3.3 № 13, повторное ревью П-5.1 № 11): генераторы строк, похожих на номер карты, для тестов фильтра
// номеров (R41, инвариант 1 приложения: реквизиты недоступны). С ВР-1 К4 их три: шестнадцатизначная строка
// (`cardLikeNumber`), годный штрихкод, похожий на номер (`gtinLookingLikeCard`), и негодный штрихкод, не похожий на
// номер (`badGtinUnlikeCard`). Общее у них одно: строка собирается **во время прогона** и в файлы не пишется.
//
// Это **не номер карты и не секрет**: настоящих номеров карт в тестах, фикстурах и коде нет и не будет (CLAUDE.md,
// «Секреты»). Строка собирается во время теста и в файлы не пишется: префикс 9 и четырнадцать одинаковых цифр — вне
// диапазонов выпуска схем карт; контрольная цифра — по алгоритму Луна, чтобы фильтр видел «похожее на номер» так же, как
// настоящий.

import { isGtin } from "@kuzin4u/agentic-core/catalog";

/** 16 цифр: «9», затем 14 раз `fill`, затем контрольная цифра Луна. `fill` — одна цифра (разные тесты — разные строки). */
export function cardLikeNumber(fill: string): string {
  if (!/^\d$/.test(fill)) throw new Error("fill — одна цифра");
  const body = "9" + fill.repeat(14);
  let sum = 0;
  for (let i = 0; i < body.length; i++) {
    let d = Number(body[body.length - 1 - i]);
    if (i % 2 === 0) d = d * 2 > 9 ? d * 2 - 9 : d * 2;
    sum += d;
  }
  return body + String((10 - (sum % 10)) % 10);
}

/**
 * Штрихкод, который **ядро признаёт годным** и который при этом похож на номер карты (ВР-1, К4).
 *
 * Зачем: решение Р-1718 выводит годный `gtin` из-под фильтра, и у этого есть названный остаточный риск (П38 п. 4) —
 * контрольная цифра GTIN считается по GS1 (веса 3 и 1), а не по Луну, и совпадения случайны и часты. Фикстура
 * показывает риск **делом**: строка проходит и `isGtin` ядра, и `hasCardNumber` приложения.
 *
 * Годность проверяет **ядро** (`isGtin`), своей проверки контрольной цифры здесь нет (Р-1511, П38 дополнение 1).
 * Подмодуль `@kuzin4u/agentic-core/catalog` закрыт стражем границы только для `src/` — в тестовой опоре он
 * разрешён, и другого источника у `isGtin` нет: ядро агента его не реэкспортирует.
 *
 * Строка собирается **во время прогона** и в файлы не пишется (CLAUDE.md, «Секреты»; Р-1699). Перебор
 * детерминированный: от `seed` вверх, шагом 1, до первого совпадения; попаданий около каждого десятого, поэтому
 * предел с запасом. Нет совпадения — исключение, а не «тихо вернём что-нибудь».
 */
export function gtinLookingLikeCard(length: 13 | 14): string {
  for (const candidate of gtins(length)) if (luhnOk(candidate)) return candidate;
  throw new Error(`не нашлось годного GTIN-${length}, похожего на номер карты`);
}

/**
 * Штрихкод, который ядро **бракует** и который на номер карты не похож (ВР-1, К4).
 *
 * Нужен, чтобы показать: фильтр — это фильтр, а не повтор вердикта ядра. Негодный штрихкод сам по себе пометки не
 * даёт; её даёт только сходство с номером. Собирается в прогоне: заглушка вида «0000000000001» в файле запрещена
 * наравне с настоящими номерами (Р-1699 снял оговорку «цифры не все одинаковые» без исключений; `guard.py` её не
 * видит — 13 цифр короче порога 15, и ровно так в фикстуру однажды уехали шестнадцать девяток). Находка ревью
 * К4 № 3.
 */
export function badGtinUnlikeCard(length: 13 | 14): string {
  for (const candidate of gtins(length)) {
    // Портим последнюю цифру: ядро такой штрихкод забракует.
    const broken = candidate.slice(0, -1) + String((Number(candidate.at(-1)) + 1) % 10);
    if (!isGtin(broken) && !luhnOk(broken)) return broken;
  }
  throw new Error(`не нашлось негодного GTIN-${length}, не похожего на номер карты`);
}

/** Годные штрихкоды нужной длины по порядку: голова от наименьшей, контрольная цифра — у ядра. */
function* gtins(length: 13 | 14): Generator<string> {
  const body = length - 1;
  const from = 10 ** (body - 1);
  for (let head = from; head < from * 10; head++) {
    const s = String(head);
    yield s + gs1Check(s);
  }
}

/** Контрольная цифра GS1 — **у ядра**: своей формулы в опоре нет, иначе она разошлась бы с `isGtin` (П38 доп. 1). */
function gs1Check(head: string): string {
  for (let d = 0; d <= 9; d++) if (isGtin(head + String(d))) return String(d);
  throw new Error("ядро не признало ни одной контрольной цифры — изменилось правило GTIN");
}

/** Проверка Луна: для теста самого генератора и для отбора штрихкодов, похожих на номер (`gtinLookingLikeCard`). */
export function luhnOk(n: string): boolean {
  let sum = 0;
  for (let i = 0; i < n.length; i++) {
    let d = Number(n[n.length - 1 - i]);
    if (i % 2 === 1) d = d * 2 > 9 ? d * 2 - 9 : d * 2;
    sum += d;
  }
  return sum % 10 === 0;
}
